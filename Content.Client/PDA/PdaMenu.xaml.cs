using Content.Client.GameTicking.Managers;
using Content.Client.Message;
using Content.Shared.PDA;
using Content.Shared.CartridgeLoader;
using Robust.Client.UserInterface;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.XAML;
using Robust.Client.UserInterface.Controls;
using Robust.Shared.Timing;
using Robust.Shared.Utility;
using Content.Shared.CCVar;
using Robust.Shared.Configuration;

namespace Content.Client.PDA;

[GenerateTypedNameReferences]
public sealed partial class PdaMenu : PdaWindow
{
    [Dependency] private readonly IClipboardManager _clipboard = default!;
    [Dependency] private readonly IGameTiming _gameTiming = default!;
    [Dependency] private readonly IEntitySystemManager _entitySystem = default!;
    private readonly ClientGameTicker _gameTicker;
    private readonly IConfigurationManager _displayConfig = IoCManager.Resolve<IConfigurationManager>();
    public const int HomeView = 0;
    public const int ProgramListView = 1;
    public const int SettingsView = 2;
    public const int ProgramContentView = 3;
    private const int PersonalView = 4;
    private const int BuiltinContentView = 5;
    private const int AppearanceView = 6;
    private string _pdaOwner = "";
    private string _owner = "";
    private string _jobTitle = "";
    private string _stationName = "";
    private string _alertLevel = "";
    private string _instructions = "";
    private int _currentView;
    private string _programTitle = "";
    private int _lastView;
    private string _lastTitle = "";

    public event Action<EntityUid>? OnProgramItemPressed;
    public event Action<EntityUid>? OnUninstallButtonPressed;
    public event Action<EntityUid>? OnInstallButtonPressed;
    public event Action<BoundUserInterfaceMessage>? OnDesktopMessage;
    public event Action? OnCartridgeClosed;
    public event Action<string>? OnHardwareAction;

    public PdaMenu()
    {
        IoCManager.InjectDependencies(this);
        _gameTicker = _entitySystem.GetEntitySystem<ClientGameTicker>();
        RobustXamlLoader.Load(this);
        Screen.EffectShader = "EclipsePdaDisplay";
        Screen.EffectsEnabled = _displayConfig.GetCVar(CCVars.PdaDisplayEffects);
        CrtEffects.Pressed = Screen.EffectsEnabled;
        CrtEffects.OnToggled += args => { Screen.EffectsEnabled = args.Pressed; _displayConfig.SetCVar(CCVars.PdaDisplayEffects, args.Pressed); };
        DesktopButton.OnPressed += _ => ToHomeScreen();
        ApplicationsButton.OnPressed += _ => ShowPage(ProgramListView, Loc.GetString("comp-pda-io-program-list-button"));
        SystemButton.OnPressed += _ => OpenSettings();
        MinimizeButton.OnPressed += _ => ToHomeScreen();
        TaskButton.OnPressed += _ => ShowPage(_lastView, _lastTitle);
        AppearanceButton.OnPressed += _ => OpenAppearance();
        AppearanceBackButton.OnPressed += _ => OpenSettings();
        ProgramCloseButton.OnPressed += _ => CloseCurrentApp();
        FlashLightToggleButton.IconTexture = FieldIcon("flashlight");
        EjectPenButton.IconTexture = FieldIcon("pen");
        EjectIdButton.IconTexture = FieldIcon("id");
        DesktopButton.IconTexture = FieldIcon("home");
        ApplicationsButton.IconTexture = FieldIcon("apps");
        SystemButton.IconTexture = FieldIcon("settings");
        FlashLightToggleButton.OnToggled += _ => OnHardwareAction?.Invoke("light");
        EjectIdButton.OnPressed += _ => OnHardwareAction?.Invoke("id");
        EjectPenButton.OnPressed += _ => OnHardwareAction?.Invoke("pen");
        EjectPaiButton.OnPressed += _ => OnHardwareAction?.Invoke("pai");
        ActivateMusicButton.OnPressed += _ => OnHardwareAction?.Invoke("music");
        AccessRingtoneButton.OnPressed += _ => OnHardwareAction?.Invoke("ringtone");
        ShowUplinkButton.OnPressed += _ => OnHardwareAction?.Invoke("uplink");
        LockUplinkButton.OnPressed += _ => OnHardwareAction?.Invoke("lock");
        PdaOwnerButton.OnPressed += _ => _clipboard.SetText(_pdaOwner);
        IdInfoButton.OnPressed += _ => _clipboard.SetText(_owner + ", " + _jobTitle);
        StationNameButton.OnPressed += _ => _clipboard.SetText(_stationName);
        StationAlertLevelButton.OnPressed += _ => _clipboard.SetText(_alertLevel);
        StationAlertLevelInstructionsButton.OnPressed += _ => _clipboard.SetText(_instructions);
        StationTimeButton.OnPressed += _ => _clipboard.SetText(StationTime());
        InitializeDesktop();
        ToHomeScreen();
    }

    private static SpriteSpecifier FieldIcon(string name) =>
        new SpriteSpecifier.Texture(new("/Textures/_Eclipse/Interface/PDA/Icons/Field/" + name + ".png"));
    public void UpdateState(PdaUpdateState state)
    {
        FlashLightToggleButton.IsActive = state.FlashlightEnabled;

        if (state.PdaOwnerInfo.ActualOwnerName != null)
        {
            _pdaOwner = state.PdaOwnerInfo.ActualOwnerName;
            PdaOwnerLabel.SetMarkup(Loc.GetString("comp-pda-ui-owner",
                ("actualOwnerName", _pdaOwner)));
            PdaOwnerLabel.Visible = true;
        }
        else
        {
            PdaOwnerLabel.Visible = false;
        }


        if (state.PdaOwnerInfo.IdOwner != null || state.PdaOwnerInfo.JobTitle != null)
        {
            _owner = state.PdaOwnerInfo.IdOwner ?? Loc.GetString("comp-pda-ui-unknown");
            _jobTitle = state.PdaOwnerInfo.JobTitle ?? Loc.GetString("comp-pda-ui-unassigned");
            IdInfoLabel.SetMarkup(Loc.GetString("comp-pda-ui",
                ("owner", _owner),
                ("jobTitle", _jobTitle)));
        }
        else
        {
            IdInfoLabel.SetMarkup(Loc.GetString("comp-pda-ui-blank"));
        }

        _stationName = state.StationName ?? Loc.GetString("comp-pda-ui-unknown");
        StationNameLabel.SetMarkup(Loc.GetString("comp-pda-ui-station",
            ("station", _stationName)));


        StationTimeLabel.SetMarkup(Loc.GetString("comp-pda-ui-station-time",
            ("time", StationTime())));

        var alertLevel = state.PdaOwnerInfo.StationAlertLevel;
        var alertColor = alertLevel == null ? PdaTheme.TextColor : state.PdaOwnerInfo.StationAlertColor;
        var alertLevelKey = alertLevel != null ? $"alert-level-{alertLevel}" : "alert-level-unknown";
        _alertLevel = alertLevel == null ? Loc.GetString("pda-info-unavailable") : Loc.GetString(alertLevelKey);

        StationAlertLevelLabel.SetMarkup(Loc.GetString(
            "comp-pda-ui-station-alert-level",
            ("color", alertColor),
            ("level", _alertLevel)
        ));
        _instructions = Loc.GetString($"{alertLevelKey}-instructions");
        StationAlertLevelInstructions.SetMarkup(Loc.GetString(
            "comp-pda-ui-station-alert-level-instructions",
            ("instructions", _instructions))
        );

        Desktop.Address = state.Address?.ToUpper() ?? "—";

        EjectIdButton.IsActive = state.PdaOwnerInfo.IdOwner != null || state.PdaOwnerInfo.JobTitle != null;
        EjectPenButton.IsActive = state.HasPen;
        EjectPaiButton.Visible = state.HasPai;
        EjectIdButton.Disabled = !EjectIdButton.IsActive;
        EjectPenButton.Disabled = !state.HasPen;
        EjectPaiButton.Disabled = !state.HasPai;
        ActivateMusicButton.Visible = state.CanPlayMusic;
        ShowUplinkButton.Visible = state.HasUplink;
        LockUplinkButton.Visible = state.HasUplink;
        DeviceSettings.Visible = state.HasPai || state.HasUplink;
    }

    private string StationTime()
    {
        if (!_gameTicker.IsGameStarted) return "00:00:00";
        var elapsed = _gameTiming.CurTime - _gameTicker.RoundStartTimeSpan;
        if (elapsed < TimeSpan.Zero) elapsed = TimeSpan.Zero;
        return $"{(int) elapsed.TotalHours:00}:{elapsed.Minutes:00}:{elapsed.Seconds:00}";
    }

    public void ToHomeScreen() => ShowPage(HomeView, "");

    private void OpenSettings() => ShowPage(SettingsView, Loc.GetString("comp-pda-io-settings-button"));

    public void HideProgramHeader()
    {
        _programTitle = "";
        if (_lastView == ProgramContentView) { _lastView = HomeView; TaskButton.Visible = false; Taskbar.Visible = false; }
        if (_currentView == ProgramContentView) ToHomeScreen();
    }

    public void ToProgramView(string title)
    {
        _programTitle = title;
        ShowPage(ProgramContentView, title);
    }

    public void ChangeView(int view) => ShowPage(view, view == ProgramContentView ? _programTitle : "");

    private void ShowPage(int view, string title)
    {
        if (view < 0 || view >= ViewContainer.ChildCount) return;
        for (var i = 0; i < ViewContainer.ChildCount; i++)
            ViewContainer.GetChild(i).Visible = i == view;
        _currentView = view;
        DesktopButton.IsCurrent = view == HomeView;
        ApplicationsButton.IsCurrent = view == ProgramListView;
        SystemButton.IsCurrent = view == SettingsView || view == AppearanceView;
        AppearanceBackButton.Visible = view == AppearanceView;
        ProgramHeader.Visible = view != HomeView;
        ProgramTitleLabel.Text = title;
        if (view != HomeView) { _lastView = view; _lastTitle = title; }
        TaskButton.Text = _lastTitle;
        TaskButton.Visible = _lastView != HomeView;
        Taskbar.Visible = false;
        RefreshTaskStrip();
        TaskLabel.Text = view == HomeView ? Desktop.Address : "";
        if (view == BuiltinContentView && _currentBuiltin != null && _builtins.TryGetValue(_currentBuiltin, out var game))
        {
            if (game is PocketBlockinatorControl blocks) blocks.GrabKeyboardFocus();
            else if (game is PocketFlappyControl flight) flight.FocusGame();
        }
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        Desktop.Owner = _pdaOwner;
        var time = StationTime();
        if (Desktop.Time == time) return;
        Desktop.Time = time;
        StationTimeLabel.SetMarkup(Loc.GetString("comp-pda-ui-station-time", ("time", time)));
    }
}
