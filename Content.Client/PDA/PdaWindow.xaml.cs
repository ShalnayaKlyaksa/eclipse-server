using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.PDA;

[Virtual]
[GenerateTypedNameReferences]
public partial class PdaWindow : BaseWindow
{

    public string? BorderColor
    {
        get => Background.ActualModulateSelf.ToHex();

        set => Background.ModulateSelfOverride = Color.FromHex(value, Color.White);
    }

    public string? AccentHColor
    {
        get => AccentH.ActualModulateSelf.ToHex();

        set
        {
            AccentH.ModulateSelfOverride = Color.FromHex(value, Color.White);
            AccentH.Visible = value != null;
        }
    }

    public string? AccentVColor
    {
        get => AccentV.ActualModulateSelf.ToHex();

        set
        {
            AccentV.ModulateSelfOverride = Color.FromHex(value, Color.White);
            AccentV.Visible = value != null;
        }
    }

    public PdaWindow()
    {
        RobustXamlLoader.Load(this);
        Stylesheet = PdaTheme.Create(IoCManager.Resolve<IUserInterfaceManager>().Stylesheet);
        Enclosure.PanelOverride = PdaTheme.Box("#161616", "#505050", radius: 14);
        ScreenWell.PanelOverride = PdaTheme.Box("#141414", "#505050", radius: 8);
        Background.PanelOverride = new Robust.Client.Graphics.StyleBoxFlat(Color.White);
        AccentH.PanelOverride = new Robust.Client.Graphics.StyleBoxFlat(Color.White);
        AccentV.PanelOverride = new Robust.Client.Graphics.StyleBoxFlat(Color.White);
        Background.ModulateSelfOverride = Color.FromHex("#FF861F");

        CloseButton.OnPressed += _ => Close();
        XamlChildren = ContentsContainer.Children;

        AccentH.Visible = false;
        AccentV.Visible = false;
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        var mode = DragMode.None;
        if (relativeMousePos.X < 6) mode |= DragMode.Left;
        if (relativeMousePos.X > Width - 6) mode |= DragMode.Right;
        if (relativeMousePos.Y < 6) mode |= DragMode.Top;
        if (relativeMousePos.Y > Height - 6) mode |= DragMode.Bottom;
        return mode != DragMode.None ? mode : relativeMousePos.Y < 40 ? DragMode.Move : DragMode.None;
    }
}
