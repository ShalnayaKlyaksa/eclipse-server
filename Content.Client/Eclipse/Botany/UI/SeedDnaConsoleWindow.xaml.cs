using Content.Shared.Eclipse.Botany.SeedDna;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Eclipse.Botany.UI;

[GenerateTypedNameReferences]
public sealed partial class SeedDnaConsoleWindow : DefaultWindow
{
    public SeedDnaConsoleWindow()
    {
        RobustXamlLoader.Load(this);
    }

    public void UpdateState(SeedDnaConsoleBoundUserInterfaceState state)
    {
        SeedButton.Text = Loc.GetString(state.IsSeedsPresent ? "seed-dna-eject-btn" : "seed-dna-insert-btn");
        SeedLabel.Text = state.SeedsName;
        DnaDiskButton.Visible = state.IsDnaDiskPresent;
        Report.RemoveAllChildren();
        foreach (var line in state.Report)
            Report.AddChild(new Label { Text = line });
    }
}
