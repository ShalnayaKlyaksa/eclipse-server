using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Administration.UI.Bwoink
{
    /// <summary>
    /// This window connects to a BwoinkSystem channel. BwoinkSystem manages the rest.
    /// </summary>
    [GenerateTypedNameReferences]
    public sealed partial class BwoinkWindow : DefaultWindow
    {
        public BwoinkWindow()
        {
            RobustXamlLoader.Load(this);

            OnOpen += () =>
            {
                Bwoink.ChannelSelector.StopFiltering();
                Bwoink.PopulateList();
            };
        }

        internal void OpenFitted(bool centered)
        {
            var available = Vector2.Max(MinSize, UserInterfaceManager.WindowRoot.Size);
            var size = Vector2.Min(SetSize, available);
            if (size != SetSize)
            {
                SetSize = size;
                centered = true;
            }

            if (centered)
                OpenCentered();
            else
                Open();
        }
    }
}
