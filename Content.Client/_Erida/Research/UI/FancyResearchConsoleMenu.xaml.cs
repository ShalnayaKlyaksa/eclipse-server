namespace Content.Client._Erida.Research.UI;

[GenerateTypedNameReferences]
public sealed partial class FancyResearchConsoleMenu : ImmersiveFancyWindow
{
    public Action<string>? OnTechnologyCardPressed;
    public Action? OnServerButtonPressed;
    public Action? OnWriteDiskPressed;
    private float _zoom = 0.85f;
    private bool _pendingFocus;
    private string? _disciplineFilter;
    private bool _factoryOnly;
    private readonly List<string> _disciplines = new();

    [Dependency] private readonly IEntityManager _entity = default!;
    [Dependency] private readonly IPrototypeManager _prototype = default!;

    private readonly SpriteSystem _sprite;

    /// <summary>
    /// Console entity
    /// </summary>
    public EntityUid Entity;

    /// <summary>
    /// Currently selected tech
    /// Exsists for better UI refreshing
    /// </summary>
    public ProtoId<TechnologyPrototype>? CurrentTech;

    /// <summary>
    /// All technologies and their availablity
    /// </summary>
    public Dictionary<string, ResearchAvailability> List = new();

    /// <summary>
    /// Cached research points
    /// </summary>
    public int Points = 0;

    /// <summary>
    /// Is tech currently being dragged
    /// </summary>
    private bool _draggin;

    /// <summary>
    /// Global position that all tech relates to.
    /// For dragging mostly
    /// </summary>
    private Vector2 _position = new Vector2(45, 250);

    public FancyResearchConsoleMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        ApplyTerminalStyle();
        InitializeSessionControls();
        _sprite = _entity.System<SpriteSystem>();
        SectionFilter.AddItem(Loc.GetString("industrial-research-all"), 0);
        SectionFilter.AddItem(Loc.GetString("industrial-research-factory"), 1);
        foreach (var discipline in _prototype.EnumeratePrototypes<TechDisciplinePrototype>().OrderBy(x => x.ID))
        {
            _disciplines.Add(discipline.ID);
            SectionFilter.AddItem(Loc.GetString(discipline.Name), _disciplines.Count + 1);
        }
        SectionFilter.OnItemSelected += args => SelectResearchSection(args.Id);
        InitializeResearchBrowser();
        ZoomText.Text = "85%";
        SectionFilter.SelectId(1);
        _factoryOnly = true;
        Search.OnTextChanged += _ => { _goalTechnology = null; GoalButton.Pressed = false; UpdatePanels(List); Recenter(); };
        ZoomIn.OnPressed += _ => SetGraphZoom(_zoom + 0.15f);
        ZoomOut.OnPressed += _ => SetGraphZoom(_zoom - 0.15f);
        DragContainer.ZoomRequested += delta => SetGraphZoom(_zoom + delta * 0.1f);
        WriteDisk.OnPressed += _ => OnWriteDiskPressed?.Invoke();
        ServerButton.OnPressed += _ => OnServerButtonPressed?.Invoke();
        DragContainer.OnKeyBindDown += OnKeybindDown;
        DragContainer.OnKeyBindUp += OnKeybindUp;
        RecenterButton.OnPressed += _ => Recenter();
        OverviewButton.OnPressed += _ => FitGraph();
        CrtEffects.OnToggled += _ => TerminalScreen.EffectsEnabled = CrtEffects.Pressed;

        UpdateInformationPanel(0);
        UpdatePanels(List);
        Recenter();
    }

    public void SelectResearchSection(int id)
    {
        if (id < 0 || id > _disciplines.Count + 1) return;
        SectionFilter.SelectId(id);
        _goalTechnology = null;
        GoalButton.Pressed = false;
        Search.Text = "";
        _factoryOnly = id == 1;
        _disciplineFilter = id >= 2 ? _disciplines[id - 2] : null;
        UpdateGraphTabs();
        UpdatePanels(List);
        Recenter();
    }

    public void SetEntity(EntityUid entity)
        => Entity = entity;

    public void UpdatePanels(Dictionary<string, ResearchAvailability> dict)
    {
        var initiallyEmpty = DragContainer.ChildCount == 0;
        DragContainer.RemoveAllChildren();
        List = dict;

        var candidates = ResearchCandidates().ToArray();
        UpdateResearchCatalog(candidates);
        var shown = candidates.Select(t => t.ID).ToHashSet();
        if (_goalTechnology != null)
            shown = ResearchMapLayout.PrerequisitePath(_goalTechnology, _technologies);
        else if (!string.IsNullOrWhiteSpace(Search.Text))
            foreach (var candidate in candidates)
                shown.UnionWith(ResearchMapLayout.PrerequisitePath(candidate.ID, _technologies));
        var visibleTechnologies = shown.Where(List.ContainsKey).Select(id => _technologies[id]).ToArray();
        _nodePositions = ResearchMapLayout.Arrange(visibleTechnologies);
        DragContainer.NodePositions = _nodePositions;
        foreach (var proto in visibleTechnologies)
        {
            var availability = List[proto.ID];
            var control = new FancyResearchConsoleItem(proto, _sprite, availability);
            control.SetZoom(_zoom);
            control.ToolTip = Loc.GetString(proto.Name) + "\n" + Loc.GetString("industrial-research-node-cost", ("points", proto.Cost));
            DragContainer.AddChild(control);
            PlaceNode(control);
            control.SelectAction += (technology, state) => SelectTech(technology, state);
            if (proto.ID == CurrentTech) SelectTech(proto, availability);
        }
        DragContainer.RebuildConnections();
        var visible = DragContainer.Children.OfType<FancyResearchConsoleItem>().ToArray();
        MapHeading.Text = Loc.GetString("industrial-research-map-count", ("count", visible.Length));
        if (!visible.Any(x => x.Prototype.ID == CurrentTech) ||
            !string.IsNullOrWhiteSpace(Search.Text) && _goalTechnology == null && !candidates.Any(t => t.ID == CurrentTech))
        {
            var first = visible.OrderBy(x => candidates.Any(t => t.ID == x.Prototype.ID) ? 0 : 1)
                .ThenBy(x => x.Availability == ResearchAvailability.Available ? 0 : 1)
                .ThenBy(x => _nodePositions[x.Prototype.ID].X).ThenBy(x => _nodePositions[x.Prototype.ID].Y).FirstOrDefault();
            if (first != null) SelectTech(first.Prototype, first.Availability);
            else { CurrentTech = null; InfoContainer.RemoveAllChildren(); }
        }
        UpdateGoalSummary();
        if (initiallyEmpty) Recenter();
    }

    public void UpdateInformationPanel(int points)
    {
        Points = points;

        var amountMsg = new FormattedMessage();
        amountMsg.AddMarkupOrThrow(Loc.GetString("research-console-menu-research-points-text",
            ("points", points)));
        ResearchAmountLabel.SetMessage(amountMsg, defaultColor: Color.FromHex("#EEEEEE"));

    }

    #region Drag handle
    protected override void MouseMove(GUIMouseMoveEventArgs args)
    {
        base.MouseMove(args);

        if (!_draggin)
            return;

        _position += args.Relative;
        DragContainer.GraphOrigin = _position;

        Relayout();
    }

    /// <summary>
    /// Raised when LMB is pressed at <see cref="DragContainer"/>
    /// </summary>
    private void OnKeybindDown(GUIBoundKeyEventArgs args)
    {
        if (args.Function == EngineKeyFunctions.Use)
            _draggin = true;
    }

    /// <summary>
    /// Raised when LMB is unpressed at <see cref="DragContainer"/>
    /// </summary>
    private void OnKeybindUp(GUIBoundKeyEventArgs args)
    {
        if (args.Function == EngineKeyFunctions.Use)
            _draggin = false;
    }

    private void OnOpenPrerequistPressed(TechnologyPrototype tech)
    {
        RevealResearch(tech.ID);
        Recenter();
    }
    // Erida end

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
        => _draggin ? DragMode.None : base.GetDragModeFor(relativeMousePos);
    #endregion

    /// <summary>
    /// Selects a tech prototype and opens info panel
    /// </summary>
    /// <param name="proto">Tech proto</param>
    /// <param name="availability">Tech availablity</param>
    public void SelectTech(TechnologyPrototype proto, ResearchAvailability availability)
    {
        InfoContainer.RemoveAllChildren();
        CurrentTech = proto.ID;
        DragContainer.SelectedTechnology = proto.ID;
        foreach (var (id, button) in _catalogButtons) button.Pressed = id == proto.ID;
        UpdateGoalSummary();
        foreach (var item in DragContainer.Children.OfType<FancyResearchConsoleItem>())
            item.SetSelected(item.Prototype.ID == proto.ID);
        var control = new FancyTechnologyInfoPanel(proto, _canResearch, availability, _sprite);
        control.BuyAction += args => OnTechnologyCardPressed?.Invoke(args.ID);
        control.OpenPrerequistAction += OnOpenPrerequistPressed;
        ApplyTerminalButtons(control);
        InfoContainer.AddChild(control);
    }

    /// <summary>
    /// Sets <see cref="_position"/> to its default value
    /// </summary>
    public void Recenter()
    {
        if (DragContainer.Width <= 0 || DragContainer.Height <= 0)
        {
            _pendingFocus = true;
            return;
        }
        _pendingFocus = false;
        var items = DragContainer.Children.OfType<FancyResearchConsoleItem>().ToArray();
        var focus = items.FirstOrDefault(x => x.Prototype.ID == CurrentTech) ??
                    items.FirstOrDefault(x => x.Availability == ResearchAvailability.Available) ?? items.FirstOrDefault();
        if (focus == null) return;
        var focusPoint = new Vector2(DragContainer.Width * .5f, DragContainer.Height * .5f);
        _position = focusPoint - (_nodePositions[focus.Prototype.ID] + new Vector2(112, 58)) * _zoom;
        Relayout();
    }

    public void FitGraph()
    {
        var items = DragContainer.Children.OfType<FancyResearchConsoleItem>().ToArray();
        if (items.Length == 0) return;
        var minimum = new Vector2(_nodePositions.Values.Min(p => p.X), _nodePositions.Values.Min(p => p.Y));
        var maximum = new Vector2(_nodePositions.Values.Max(p => p.X), _nodePositions.Values.Max(p => p.Y)) + new Vector2(224, 116);
        var extent = maximum - minimum;
        SetGraphZoom(MathF.Min((DragContainer.Width - 48) / extent.X, (DragContainer.Height - 48) / extent.Y));
        _position = new Vector2(24, 40) - minimum * _zoom;
        Relayout();
    }

    public void SetGraphZoom(float zoom)
    {
        zoom = Math.Clamp(zoom, 0.55f, 1.25f);
        var center = DragContainer.Size / 2;
        _position = center + (_position - center) * (zoom / _zoom);
        _zoom = zoom;
        ZoomText.Text = $"{_zoom * 100:0}%";
        Relayout();
    }

    private void Relayout()
    {
        DragContainer.GraphOrigin = _position;
        DragContainer.GraphZoom = _zoom;
        foreach (var item in DragContainer.Children.OfType<FancyResearchConsoleItem>())
        {
            item.SetZoom(_zoom);
            PlaceNode(item);
        }
    }

    private void PlaceNode(FancyResearchConsoleItem item)
    {
        var position = item.PlaceInViewport(_position + _nodePositions[item.Prototype.ID] * _zoom, DragContainer.Size);
        // Absolute margins avoid SetPosition's relative delta while an arrange pass is in progress.
        LayoutContainer.SetMarginLeft(item, position.X);
        LayoutContainer.SetMarginTop(item, position.Y);
        LayoutContainer.SetMarginRight(item, position.X + item.MinSize.X);
        LayoutContainer.SetMarginBottom(item, position.Y + item.MinSize.Y);
    }

    private Vector2 _lastGraphSize;

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateSessionLayout();
        if (_lastGraphSize != DragContainer.Size)
        {
            if (_lastGraphSize.X > 0 && _lastGraphSize.Y > 0)
                _position += (DragContainer.Size - _lastGraphSize) * new Vector2(.5f, .5f);
            _lastGraphSize = DragContainer.Size;
            Relayout();
        }
        // Defer the initial camera until layout has completed; resizing callbacks run inside Arrange.
        if (_pendingFocus && DragContainer.Width > 0 && DragContainer.Height > 0) Recenter();
    }

    public override void Close()
    {
        base.Close();

        DragContainer.RemoveAllChildren();
        InfoContainer.RemoveAllChildren();
    }

}
