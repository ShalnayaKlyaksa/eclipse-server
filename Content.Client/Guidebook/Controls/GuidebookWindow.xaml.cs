namespace Content.Client.Guidebook.Controls;

[GenerateTypedNameReferences]
public sealed partial class GuidebookWindow : BaseWindow, ILinkClickHandler, IAnchorClickHandler
{
    [Dependency] private readonly DocumentParsingManager _parsingMan = default!;
    [Dependency] private readonly IResourceManager _resourceManager = default!;
    [Dependency] private readonly IPrototypeManager _prototypes = default!;
    private readonly ISawmill _sawmill;
    private GuidebookCatalog _catalog = new([], _ => "", _ => "");
    private Dictionary<ProtoId<GuideEntryPrototype>, GuideEntry> _entries = new();
    private readonly Dictionary<ResPath, string> _documents = new();
    private readonly HashSet<string> _bookmarks = new();
    private static readonly ResPath BookmarkPath = new("/guidebook-bookmarks.txt");
    private readonly List<View> _history = new();
    private View _view = new(ViewKind.Catalog);
    private int _historyIndex = -1;
    private bool _updating;
    private float _searchDelay = -1;
    private bool _expanded;
    private Vector2 _normalSize;
    private Vector2 _normalPosition;
    private string? _forcedRoot;
    public ProtoId<GuideEntryPrototype> LastEntry;

    private enum ViewKind { Article, Catalog, Search, Bookmarks }
    private sealed record View(ViewKind Kind, string? Id = null, string? Branch = null, string Query = "", int Page = 0,
        float Scroll = 0, string Filter = "");

    public GuidebookWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sawmill = Logger.GetSawmill("guidebook");
        ApplyStyles();
        CatalogButton.OnPressed += _ => Navigate(new View(ViewKind.Catalog));
        BookmarksButton.OnPressed += _ => Navigate(new View(ViewKind.Bookmarks, Branch: _view.Branch));
        UpButton.OnPressed += _ => OpenCatalog(_view.Branch == null ? null : _catalog.Parent(_view.Branch));
        BackButton.OnPressed += _ => Travel(-1);
        ForwardButton.OnPressed += _ => Travel(1);
        BookmarkButton.OnPressed += _ => ToggleBookmark();
        CloseButton.OnPressed += _ => Close();
        ExpandButton.OnPressed += _ => ToggleExpanded();
        SearchBar.OnTextChanged += _ => { if (!_updating) _searchDelay = 0.15f; };
        SearchBar.OnTextEntered += _ => Search();
        ClearSearchButton.OnPressed += _ =>
        {
            _searchDelay = -1;
            if (_view.Kind == ViewKind.Search && _historyIndex > 0) Travel(-1);
            else OpenCatalog(null);
        };
        ArticleFilter.OnTextChanged += _ => { if (!_updating) FilterArticle(); };
        ReadBookmarks();
    }

    public void OpenGuide()
    {
        var available = Vector2.Max(new Vector2(1), UserInterfaceManager.WindowRoot.Size - new Vector2(24));
        MinSize = Vector2.Min(new Vector2(640, 440), available);
        if (!IsOpen) SetSize = Vector2.Min(new Vector2(1100, 800), available);
        OpenCentered();
    }

    public override void Close()
    {
        RememberPosition();
        SearchBar.ReleaseKeyboardFocus();
        ArticleFilter.ReleaseKeyboardFocus();
        base.Close();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (_searchDelay >= 0 && (_searchDelay -= args.DeltaSeconds) <= 0) Search();
        if (_expanded && Root != null)
        {
            SetSize = Root.Size;
            LayoutContainer.SetPosition(this, Vector2.Zero);
        }
    }

    private void ToggleExpanded()
    {
        if (Root == null) return;
        if (!_expanded)
        {
            _normalSize = Size;
            _normalPosition = Position;
            _expanded = true;
            SetSize = Root.Size;
            LayoutContainer.SetPosition(this, Vector2.Zero);
        }
        else
        {
            _expanded = false;
            SetSize = _normalSize;
            LayoutContainer.SetPosition(this, _normalPosition);
        }
    }

    protected override DragMode GetDragModeFor(Vector2 point)
    {
        if (_expanded) return DragMode.None;
        var mode = DragMode.None;
        if (point.X < 6) mode |= DragMode.Left;
        else if (point.X > Size.X - 6) mode |= DragMode.Right;
        if (point.Y < 6) mode |= DragMode.Top;
        else if (point.Y > Size.Y - 6) mode |= DragMode.Bottom;
        return mode != DragMode.None ? mode : point.Y < 65 ? DragMode.Move : DragMode.None;
    }

    public void UpdateGuides(Dictionary<ProtoId<GuideEntryPrototype>, GuideEntry> entries,
        List<ProtoId<GuideEntryPrototype>>? rootEntries = null, ProtoId<GuideEntryPrototype>? forceRoot = null,
        ProtoId<GuideEntryPrototype>? selected = null, bool resume = false)
    {
        var sameBook = _entries.Keys.ToHashSet().SetEquals(entries.Keys) && _forcedRoot == forceRoot?.Id;
        _entries = entries;
        _forcedRoot = forceRoot?.Id;
        var core = UserInterfaceManager.GetUIController<InfoUIController>().GetCoreRuleEntry().Id;
        var available = entries.Values.Where(e => !e.RuleEntry || e.Id == core).ToList();
        _catalog = new GuidebookCatalog(available, e => Loc.GetString(e.Name), SearchText,
            rootEntries?.Select(id => id.Id), forceRoot?.Id);
        if (resume && sameBook && _history.Count != 0) { Render(); return; }
        _history.Clear();
        _historyIndex = -1;
        var id = selected?.Id;
        if (entries.Count == 1) id = entries.Keys.First().Id;
        if (id != null && entries.ContainsKey(id)) OpenArticle(id);
        else Navigate(new View(ViewKind.Catalog));
    }

    public void ClearSelectedGuide() => OpenCatalog(null);
    public void HandleClick(string link) => OpenArticle(link);

    internal void SearchFor(string query)
    {
        SearchBar.Text = query;
        Search();
    }

    private void OpenArticle(string id, string filter = "")
    {
        if (!_entries.ContainsKey(id)) return;
        Navigate(new View(ViewKind.Article, id, _catalog.Children(id).Count > 0 ? id : _catalog.Parent(id),
            Filter: _entries[id].FilterEnabled ? filter : ""));
    }
    private void OpenCatalog(string? id)
    {
        if (id != null && _catalog.Entries.TryGetValue(id, out var entry) && entry.OpenArticleFromCatalog)
        {
            OpenArticle(id);
            return;
        }

        Navigate(new View(ViewKind.Catalog, Branch: id));
    }
    private void RememberPosition()
    {
        if (_historyIndex < 0) return;
        _view = _view with { Scroll = Scroll.VScroll, Filter = ArticleFilter.Text };
        _history[_historyIndex] = _view;
    }
    private void Navigate(View view, bool replace = false)
    {
        RememberPosition();
        _view = view;
        if (replace && _historyIndex >= 0) _history[_historyIndex] = view;
        else
        {
            if (_historyIndex + 1 < _history.Count) _history.RemoveRange(_historyIndex + 1, _history.Count - _historyIndex - 1);
            _history.Add(view);
            _historyIndex++;
        }
        Render();
    }
    private void Travel(int direction)
    {
        var target = _historyIndex + direction;
        if (target < 0 || target >= _history.Count) return;
        RememberPosition();
        _view = _history[_historyIndex = target];
        Render();
    }
    private void Search()
    {
        _searchDelay = -1;
        var query = SearchBar.Text.Trim();
        if (query.Length == 0)
        {
            if (_view.Kind == ViewKind.Search && _historyIndex > 0) Travel(-1);
            return;
        }
        Navigate(new View(ViewKind.Search, Branch: _view.Branch, Query: query), _view.Kind == ViewKind.Search);
    }

    private void Render()
    {
        _updating = true;
        _searchDelay = -1;
        SearchBar.Text = _view.Kind == ViewKind.Search ? _view.Query : "";
        ClearSearchButton.Visible = SearchBar.Text.Length != 0;
        ArticleFilter.Text = _view.Filter;
        FilterContainer.Visible = false;
        BookmarkButton.Visible = _view.Kind == ViewKind.Article;
        BookmarkButton.Pressed = _view.Id != null && _bookmarks.Contains(_view.Id);
        BookmarkButton.Text = Loc.GetString(BookmarkButton.Pressed ? "guidebook-bookmarked" : "guidebook-add-bookmark");
        BackButton.Disabled = _historyIndex <= 0;
        ForwardButton.Disabled = _historyIndex >= _history.Count - 1;
        EntryContainer.RemoveAllChildren();
        RenderBranch();
        RenderBreadcrumbs();
        switch (_view.Kind)
        {
            case ViewKind.Article: ShowGuide(_entries[_view.Id!]); break;
            case ViewKind.Catalog: RenderCatalog(); break;
            case ViewKind.Search: RenderSearch(); break;
            case ViewKind.Bookmarks:
                AddHeading(Loc.GetString("guidebook-bookmarks"));
                var saved = _bookmarks.Where(_catalog.Entries.ContainsKey).OrderBy(_catalog.Title).ToList();
                foreach (var id in saved) AddResult(id);
                if (saved.Count == 0) EntryContainer.AddChild(Paragraph(Loc.GetString("guidebook-no-bookmarks")));
                break;
        }
        Footer.Text = Loc.GetString(_view.Kind == ViewKind.Article ? "guidebook-single-article" : "guidebook-entry-count",
            ("count", _catalog.Entries.Count));
        _updating = false;
        Scroll.SetScrollValue(Vector2.Zero);
        var view = _view;
        UserInterfaceManager.DeferAction(() => { if (view == _view) Scroll.VScroll = view.Scroll; });
    }

    private void RenderBranch()
    {
        BranchList.RemoveAllChildren();
        var branch = _view.Branch;
        BranchTitle.Text = branch == null ? Loc.GetString("guidebook-all-sections") : _catalog.Title(branch);
        UpButton.Visible = branch != null;
        if (branch != null)
            BranchList.AddChild(NavButton(Loc.GetString("guidebook-section-overview"), () => OpenArticle(branch),
                _view.Kind == ViewKind.Article && _view.Id == branch));
        foreach (var id in _catalog.Children(branch))
        {
            var hasChildren = _catalog.Children(id).Count > 0;
            var button = NavButton(_catalog.Title(id) + (hasChildren ? "  ›" : ""),
                () => { if (hasChildren) OpenCatalog(id); else OpenArticle(id); },
                _view.Kind == ViewKind.Article && _view.Id == id);
            button.ToolTip = _catalog.Title(id);
            BranchList.AddChild(button);
        }
        EntryCount.Text = Loc.GetString("guidebook-entry-count", ("count", _catalog.Entries.Count));
    }
    private void RenderBreadcrumbs()
    {
        Breadcrumbs.RemoveAllChildren();
        Breadcrumbs.AddChild(MakeButton(Loc.GetString("guidebook-catalog"), () => OpenCatalog(null), "GuidebookLink"));
        var id = _view.Kind == ViewKind.Article ? _view.Id : _view.Branch;
        if (id == null) return;
        // Keep the complete path in the tooltip when a deep hierarchy cannot fit the toolbar.
        var path = _catalog.Ancestors(id);
        foreach (var parent in path.TakeLast(SetSize.X >= 1000 ? 2 : 1))
        {
            Breadcrumbs.AddChild(new Label { Text = "›", StyleClasses = { "GuidebookMuted" } });
            var button = MakeButton(_catalog.Title(parent), () => OpenCatalog(parent), "GuidebookLink");
            button.ClipText = true;
            button.SetWidth = 105;
            button.ToolTip = _catalog.Title(parent);
            Breadcrumbs.AddChild(button);
        }
        Breadcrumbs.AddChild(new Label { Text = "›" });
        Breadcrumbs.AddChild(new Label { Text = _catalog.Title(id), ClipText = true, HorizontalExpand = true,
            ToolTip = _catalog.Path(id) + " / " + _catalog.Title(id), StyleClasses = { "GuidebookMuted" } });
    }
    private void RenderCatalog()
    {
        var branch = _view.Branch;
        AddHeading(branch == null ? Loc.GetString("guidebook-catalog") : _catalog.Title(branch));
        EntryContainer.AddChild(Paragraph(Loc.GetString("guidebook-catalog-hint")));
        if (branch != null) EntryContainer.AddChild(MakeButton(Loc.GetString("guidebook-section-overview"), () => OpenArticle(branch), "GuidebookLink"));
        foreach (var id in _catalog.Children(branch)) AddResult(id, catalog: true);
    }
    private void RenderSearch()
    {
        const int pageSize = 8;
        var results = _catalog.Search(_view.Query);
        var pages = Math.Max(1, (results.Count + pageSize - 1) / pageSize);
        var page = Math.Min(_view.Page, pages - 1);
        AddHeading(Loc.GetString("guidebook-search-results"));
        EntryContainer.AddChild(Paragraph(Loc.GetString("guidebook-search-count", ("count", results.Count), ("query", _view.Query))));
        foreach (var id in results.Skip(page * pageSize).Take(pageSize)) AddResult(id, _catalog.Snippet(id, _view.Query));
        if (results.Count == 0) EntryContainer.AddChild(Paragraph(Loc.GetString("guidebook-no-results")));
        var paging = new BoxContainer();
        paging.AddChild(MakeButton(Loc.GetString("guidebook-previous"), () => Navigate(_view with { Page = page - 1, Scroll = 0 }, true)));
        ((Button) paging.GetChild(0)).Disabled = page == 0;
        paging.AddChild(new Label { Text = $"{page + 1} / {pages}", HorizontalExpand = true, HorizontalAlignment = HAlignment.Center });
        var next = MakeButton(Loc.GetString("guidebook-next"), () => Navigate(_view with { Page = page + 1, Scroll = 0 }, true));
        next.Disabled = page >= pages - 1;
        paging.AddChild(next);
        EntryContainer.AddChild(paging);
    }
    private void AddResult(string id, string? snippet = null, bool catalog = false)
    {
        var button = new ContainerButton { HorizontalExpand = true, StyleClasses = { "GuidebookResult" } };
        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 5 };
        box.AddChild(Paragraph(_catalog.Title(id), Accent));
        var path = _catalog.Path(id);
        if (path.Length > 0) box.AddChild(Paragraph(path, Muted));
        if (!string.IsNullOrEmpty(snippet)) box.AddChild(Paragraph(snippet, Ink));
        button.AddChild(box);
        button.OnPressed += _ =>
        {
            if (catalog && _catalog.Children(id).Count > 0) OpenCatalog(id);
            else OpenArticle(id, _view.Kind == ViewKind.Search && !_view.Query.Any(char.IsWhiteSpace) ? _view.Query : "");
        };
        EntryContainer.AddChild(button);
    }
    private void AddHeading(string text) => EntryContainer.AddChild(new Label { Text = text, StyleClasses = { "LabelHeadingBigger" } });

    private void ShowGuide(GuideEntry entry)
    {
        var markup = GetDocument(entry);
        if (markup.Length == 0)
        {
            EntryContainer.AddChild(Paragraph(Loc.GetString("guidebook-read-error")));
            return;
        }
        _parsingMan.TryAddMarkup(EntryContainer, markup);
        foreach (var label in EntryContainer.GetControlOfType<Label>(true))
            if (label.StyleClasses.Contains("GuidebookTextLink")) label.FontColorOverride = Accent;
        LastEntry = entry.Id;
        FilterContainer.Visible = entry.FilterEnabled;
        var (representations, links) = GetLinkableControlsAndLinks(EntryContainer);
        var available = representations.Select(c => c.RepresentedPrototype).Where(p => p != null).ToHashSet();
        foreach (var link in links)
            if (link.LinkedPrototype != null && available.Contains(link.LinkedPrototype)) link.EnablePrototypeLink();
        FilterArticle();
    }
    private void FilterArticle()
    {
        foreach (var element in EntryContainer.GetSearchableControls()) element.SetHiddenState(true, ArticleFilter.Text.Trim());
    }
    public void HandleAnchor(IPrototypeLinkControl prototypeLinkControl)
    {
        var target = prototypeLinkControl.LinkedPrototype;
        if (target == null) return;
        var (representations, _) = GetLinkableControlsAndLinks(EntryContainer);
        foreach (var representation in representations)
        {
            if (representation.RepresentedPrototype != target || representation is not Control control) continue;
            control.Visible = true;
            for (var parent = control.Parent; parent != null; parent = parent.Parent)
                if (parent is Collapsible foldout) foldout.BodyVisible = true;
            UserInterfaceManager.DeferAction(() =>
            {
                if (control.GetControlScrollPosition() is {} position) Scroll.VScrollTarget = position.Y;
            });
            break;
        }
    }
    private static (List<IPrototypeRepresentationControl>, List<IPrototypeLinkControl>) GetLinkableControlsAndLinks(Control parent)
    {
        var representations = new List<IPrototypeRepresentationControl>();
        var links = new List<IPrototypeLinkControl>();
        foreach (var child in parent.Children)
        {
            if (child is IPrototypeLinkControl link) links.Add(link);
            else if (child is IPrototypeRepresentationControl representation) representations.Add(representation);
            var (nestedRepresentations, nestedLinks) = GetLinkableControlsAndLinks(child);
            representations.AddRange(nestedRepresentations);
            links.AddRange(nestedLinks);
        }
        return (representations, links);
    }
    private void ToggleBookmark()
    {
        if (_view.Id == null) return;
        if (!_bookmarks.Add(_view.Id)) _bookmarks.Remove(_view.Id);
        try
        {
            using var writer = _resourceManager.UserData.OpenWriteText(BookmarkPath);
            foreach (var id in _bookmarks.Order()) writer.WriteLine(id);
        }
        catch (IOException e) { _sawmill.Warning($"Could not save guidebook bookmarks: {e.Message}"); }
        BookmarkButton.Pressed = _bookmarks.Contains(_view.Id);
        BookmarkButton.Text = Loc.GetString(BookmarkButton.Pressed ? "guidebook-bookmarked" : "guidebook-add-bookmark");
    }
    private void ReadBookmarks()
    {
        try
        {
            if (!_resourceManager.UserData.Exists(BookmarkPath)) return;
            using var reader = _resourceManager.UserData.OpenText(BookmarkPath);
            while (reader.ReadLine() is {} line)
                if (line.Length > 0) _bookmarks.Add(line);
        }
        catch (IOException e) { _sawmill.Warning($"Could not read guidebook bookmarks: {e.Message}"); }
    }
}
