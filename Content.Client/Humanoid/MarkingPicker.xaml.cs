    {
        return new Label
        {
            Text = text.ToUpperInvariant(),
            StyleIdentifier = MainMenuControl.StyleIdentifierCompactHeaderGold,
        };
    }

    private Label CreateEmptyLabel(string text)
    {
        return new Label
        {
            Text = text,
            StyleIdentifier = MainMenuControl.StyleIdentifierCompactSubtle,
            Margin = new Thickness(4),
        };
    }

    private PanelContainer CreatePanel(float? width)
    {
        var panel = new PanelContainer
        {
            HorizontalExpand = width is null,
            VerticalExpand = true,
            PanelOverride = BorderedPanel(PanelColor, BorderColor),
        };

        if (width is { } setWidth)
            panel.SetWidth = setWidth;

        return panel;
    }

    private PanelContainer CreateCard(bool selected)
    {
        return new PanelContainer
        {
            HorizontalExpand = true,
            PanelOverride = BorderedPanel(selected ? CardSelectedColor : CardColor, selected ? AccentColor : BorderColor),
        };
    }

    private Label CreateTag(string text)
    {
        return new Label
        {
            Text = text,
            StyleIdentifier = MainMenuControl.StyleIdentifierCompactSubtle,
            Modulate = MutedTextColor,
        };
    }

    private Control CreateDivider()
    {
        return new PanelContainer
        {
            MinHeight = 1,
            HorizontalExpand = true,
            PanelOverride = new StyleBoxFlat(BorderColor),
        };
    }

    private StyleBoxFlat BorderedPanel(Color background, Color border)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = background,
            BorderColor = border,
            BorderThickness = new Thickness(1),
        };
    }

    private ZoneDefinition CurrentZone => Zones.First(zone => zone.Zone == _selectedZone);

