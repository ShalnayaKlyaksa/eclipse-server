    public void SetModel(MarkingsViewModel model)
    {
        if (_markingsModel == model)
            return;

        UnsubscribeModel();
        _markingsModel = model;
        SubscribeModel();
        RebuildAll();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        SubscribeModel();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        UnsubscribeModel();
    }

    protected override void Resized()
    {
        base.Resized();

        ApplyResponsiveLayout();
    }

    private void ApplyResponsiveLayout()
    {
        var compact = Width < RightPanelBreakpoint;
        var veryCompact = Width < VeryCompactBreakpoint;

        var leftWidth = veryCompact
            ? LeftPanelWidthVeryCompact
            : compact
                ? LeftPanelWidthCompact
                : LeftPanelWidth;
        var rightWidth = Width < RightPanelShrinkBreakpoint ? RightPanelWidthCompact : RightPanelWidth;
        var rightVisible = !compact;

        _leftPanel.SetWidth = leftWidth;
        _rightPanel.Visible = rightVisible;
        _rightPanel.SetWidth = rightWidth;

        // Whatever the middle column is left with once the side panels and the separations have taken their share.
        var middleWidth = Width - leftWidth - RootSeparation
                          - (rightVisible ? rightWidth + RootSeparation : 0f);

        var compactEntries = middleWidth < CompactEntryWidth;
        var compactNav = Height < CompactNavHeight;

        if (compactNav != _compactNav)
        {
            _compactNav = compactNav;
            RebuildZoneButtons();
            RebuildFilterButtons();
        }

        if (compactEntries != _compactEntries)
        {
            _compactEntries = compactEntries;
            RebuildAvailableItems();
            RebuildSelectedItems();
        }
    }

    private void SubscribeModel()
    {
        if (_markingsModel is null || _subscribed)
            return;

        _markingsModel.OrganDataChanged += RebuildAll;
        _markingsModel.OrganProfileDataChanged += OnOrganProfileDataChanged;
        _markingsModel.EnforcementsChanged += RebuildAll;
        _markingsModel.MarkingsReset += RebuildAll;
        _markingsModel.MarkingsChanged += OnMarkingsChanged;
        _subscribed = true;
    }

    private void UnsubscribeModel()
    {
        if (_markingsModel is null || !_subscribed)
            return;

        _markingsModel.OrganDataChanged -= RebuildAll;
        _markingsModel.OrganProfileDataChanged -= OnOrganProfileDataChanged;
        _markingsModel.EnforcementsChanged -= RebuildAll;
        _markingsModel.MarkingsReset -= RebuildAll;
        _markingsModel.MarkingsChanged -= OnMarkingsChanged;
        _subscribed = false;
    }

    private void OnOrganProfileDataChanged(bool refresh)
    {
        if (refresh)
            RebuildAll();
    }

    private void OnMarkingsChanged(ProtoId<OrganCategoryPrototype> organ, HumanoidVisualLayers layer)
    {
        if (!CurrentZone.Layers.Contains(layer))
            return;

        RebuildAvailableItems();
        RebuildSelectedItems();
    }

    private void RebuildAll()
    {
        RebuildZoneButtons();
        RebuildFilterButtons();
        RebuildAvailableItems();
        RebuildSelectedItems();
    }

    private void RebuildZoneButtons()
    {
        _zoneButtons.RemoveAllChildren();
        _zoneButtons.SeparationOverride = _compactNav ? NavSeparationCompact : NavSeparation;

        foreach (var zone in Zones)
        {
            var selected = zone.Zone == _selectedZone;
            var button = new Button
            {
                Text = selected
                    ? $"▶  {zone.Icon}  {zone.Label}"
                    : $"   {zone.Icon}  {zone.Label}",
                HorizontalExpand = true,
                MinHeight = _compactNav ? NavButtonHeightCompact : NavButtonHeight,
                TextAlign = Label.AlignMode.Left,
                StyleIdentifier = selected ? MainMenuControl.StyleIdentifierPrimary : MainMenuControl.StyleIdentifierSecondary,
                ClipText = true,
            };
            button.OnPressed += _ =>
            {
                _selectedZone = zone.Zone;
                if (_selectedZone != BodyZone.Head && IsHeadOnlyFilter(_selectedFilter))
                    _selectedFilter = MarkingFilter.All;
                RebuildAll();
            };
            _zoneButtons.AddChild(button);
        }
    }

    private void RebuildFilterButtons()
    {
        _filterButtons.RemoveAllChildren();
        _filterButtons.SeparationOverride = _compactNav ? NavSeparationCompact : NavSeparation;

        foreach (var filter in Filters)
        {
            if (_selectedZone != BodyZone.Head && IsHeadOnlyFilter(filter.Filter))
                continue;

            var selected = filter.Filter == _selectedFilter;
            var button = new Button
            {
                Text = selected ? $"▶  {filter.Label}" : $"   {filter.Label}",
                HorizontalExpand = true,
                MinHeight = _compactNav ? NavButtonHeightCompact : NavButtonHeight,
                TextAlign = Label.AlignMode.Left,
                StyleIdentifier = selected ? MainMenuControl.StyleIdentifierPrimary : MainMenuControl.StyleIdentifierSecondary,
                ClipText = true,
            };
            button.OnPressed += _ =>
            {
                _selectedFilter = filter.Filter;
                RebuildFilterButtons();
                RebuildAvailableItems();
                RebuildSelectedItems();
            };
            _filterButtons.AddChild(button);
        }
    }

    private void RebuildAvailableItems()
    {
        _availableItems.RemoveAllChildren();

        if (_markingsModel is null)
            return;

        var query = _searchBar.Text.Trim();
        var entries = GetAvailableEntries()
            .Where(MatchesFilter)
            .Where(entry => MatchesSearch(entry.Prototype, query))
            .OrderBy(entry => GetMarkingName(entry.Prototype), StringComparer.CurrentCultureIgnoreCase)
            .ToList();

        if (entries.Count == 0)
        {
            _availableItems.AddChild(CreateEmptyLabel("Нет доступных черт для выбранной зоны."));
            return;
        }

        foreach (var entry in entries)
        {
            _availableItems.AddChild(CreateAvailableEntry(entry));
        }
    }

    private void RebuildSelectedItems()
    {
        _selectedItems.RemoveAllChildren();

        if (_markingsModel is null)
        {
            _selectedCount.Text = "Выбрано: 0";
            return;
        }

        var selected = GetSelectedEntries().Where(MatchesFilter).ToList();
        _selectedCount.Text = $"Выбрано: {selected.Count}";

        if (selected.Count == 0)
        {
            _selectedItems.AddChild(CreateEmptyLabel("Выберите черту из списка слева."));
            return;
        }

        foreach (var group in selected.GroupBy(entry => GetLayerName(entry.Layer)).OrderBy(group => group.Key))
        {
            var groupHeader = new Label
            {
                Text = "▾ " + group.Key.ToUpperInvariant(),
                StyleIdentifier = MainMenuControl.StyleIdentifierCompactHeaderGold,
                Margin = new Thickness(0, 8, 0, 0),
            };
            _selectedItems.AddChild(groupHeader);

            foreach (var entry in group)
            {
                _selectedItems.AddChild(CreateSelectedEntry(entry));
            }
        }
    }

    private Control CreateAvailableEntry(MarkingEntry entry)
    {
        var selected = _markingsModel?.IsMarkingSelected(entry.Organ, entry.Layer, entry.Prototype.ID) == true;
        var panel = new Button
        {
            HorizontalExpand = true,
            StyleIdentifier = selected ? MainMenuControl.StyleIdentifierPrimary : MainMenuControl.StyleIdentifierSecondary,
        };
        panel.MinHeight = _compactEntries ? 56 : 84;
        panel.OnPressed += _ => ToggleMarking(entry, selected);

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = _compactEntries ? 6 : 10,
            HorizontalExpand = true,
            VerticalExpand = true,
            Margin = new Thickness(_compactEntries ? 5 : 8),
        };
        panel.AddChild(row);

        row.AddChild(CreatePreview(entry.Prototype, _compactEntries ? 40 : 64));

        var textColumn = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            VerticalAlignment = VAlignment.Center,
            HorizontalExpand = true,
        };
        var name = new Label
        {
            Text = GetMarkingName(entry.Prototype),
            StyleIdentifier = MainMenuControl.StyleIdentifierCompactText,
            ClipText = true,
        };
        textColumn.AddChild(name);

        // The tag row cannot clip (its labels size themselves), so on a narrow column it is dropped rather than
        // pushing the name out of view. The same information is in the zone and filter selection anyway.
        if (!_compactEntries)
        {
            var tags = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 6,
                Margin = new Thickness(0, 6, 0, 0),
            };
            tags.AddChild(CreateTag(GetFilterLabel(entry.Prototype)));
            tags.AddChild(CreateTag(GetLayerName(entry.Layer)));
            foreach (var species in GetSpeciesTags(entry.Prototype))
            {
                tags.AddChild(CreateTag(species));
            }
            textColumn.AddChild(tags);
        }

        row.AddChild(textColumn);

        row.AddChild(new Label
        {
            Text = selected ? "OK" : "+",
            MinWidth = _compactEntries ? 26 : 48,
            VerticalAlignment = VAlignment.Center,
            StyleIdentifier = selected ? MainMenuControl.StyleIdentifierPrimary : MainMenuControl.StyleIdentifierCompactButton,
        });

        return panel;
    }

    private void ToggleMarking(MarkingEntry entry, bool selected)
    {
        if (_markingsModel is null)
            return;

        if (selected)
            _markingsModel.TryDeselectMarking(entry.Organ, entry.Layer, entry.Prototype.ID);
        else
            _markingsModel.TrySelectMarking(entry.Organ, entry.Layer, entry.Prototype.ID);
    }

    private Control CreateSelectedEntry(MarkingEntry entry)
    {
        var panel = CreateCard(false);
        panel.MinHeight = _compactEntries ? 48 : 64;

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = _compactEntries ? 6 : 10,
            HorizontalExpand = true,
            Margin = new Thickness(_compactEntries ? 5 : 8),
        };
        panel.AddChild(row);

        row.AddChild(CreatePreview(entry.Prototype, _compactEntries ? 34 : 48));
        row.AddChild(new Label
        {
            Text = GetMarkingName(entry.Prototype),
            StyleIdentifier = MainMenuControl.StyleIdentifierCompactText,
            VerticalAlignment = VAlignment.Center,
            HorizontalExpand = true,
            ClipText = true,
        });

        var remove = new Button
        {
            Text = "X",
            MinWidth = 40,
            StyleIdentifier = MainMenuControl.StyleIdentifierCompactButton,
            VerticalAlignment = VAlignment.Center,
        };
        remove.OnPressed += _ => _markingsModel?.TryDeselectMarking(entry.Organ, entry.Layer, entry.Prototype.ID);
        row.AddChild(remove);

        return panel;
    }

    private IEnumerable<MarkingEntry> GetAvailableEntries()
    {
        if (_markingsModel is null)
            yield break;

        foreach (var (organ, organData) in _markingsModel.OrganData)
        {
            if (!_markingsModel.OrganProfileData.TryGetValue(organ, out var organProfileData))
                continue;

            foreach (var layer in organData.Layers)
            {
                if (!CurrentZone.Layers.Contains(layer))
                    continue;

                var markings = _markingsModel.EnforceGroupAndSexRestrictions
                    ? _marking.MarkingsByLayerAndSpeciesGroupAndSex(layer, _markingsModel.Species, organData.Group, organProfileData.Sex)
                    : _marking.MarkingsByLayer(layer);

                foreach (var marking in markings.Values)
                {
                    yield return new MarkingEntry(organ, layer, marking);
                }
            }
        }
    }

    private IEnumerable<MarkingEntry> GetSelectedEntries()
    {
        if (_markingsModel is null)
            yield break;

        foreach (var (organ, organMarkings) in _markingsModel.Markings)
        {
            foreach (var (layer, markings) in organMarkings)
            {
                if (!CurrentZone.Layers.Contains(layer))
                    continue;

                foreach (var marking in markings)
                {
                    if (_prototype.TryIndex<MarkingPrototype>(marking.MarkingId, out var markingProto))
                        yield return new MarkingEntry(organ, layer, markingProto);
                }
            }
        }
    }

    private void ClearSelectedZone()
    {
        if (_markingsModel is null)
            return;

        foreach (var entry in GetSelectedEntries().ToList())
        {
            _markingsModel.TryDeselectMarking(entry.Organ, entry.Layer, entry.Prototype.ID);
        }
    }

    private bool MatchesSearch(MarkingPrototype prototype, string query)
    {
        if (string.IsNullOrWhiteSpace(query))
            return true;

        return GetMarkingName(prototype).Contains(query, StringComparison.OrdinalIgnoreCase) ||
               prototype.ID.Contains(query, StringComparison.OrdinalIgnoreCase);
    }

    private bool MatchesFilter(MarkingEntry entry)
    {
        return _selectedFilter switch
        {
            MarkingFilter.All => true,
            MarkingFilter.Scars => IsScar(entry.Prototype),
            MarkingFilter.Bandages => IsBandage(entry.Prototype),
            MarkingFilter.Special => !IsScar(entry.Prototype) && !IsBandage(entry.Prototype),
            MarkingFilter.Face => entry.Layer is HumanoidVisualLayers.Snout or HumanoidVisualLayers.SnoutCover,
            MarkingFilter.Eyes => entry.Layer == HumanoidVisualLayers.Eyes,
            MarkingFilter.UpperEars => (entry.Layer is HumanoidVisualLayers.HeadTop or HumanoidVisualLayers.HeadSide) && IsEar(entry.Prototype),
            MarkingFilter.LowerEars => entry.Layer == HumanoidVisualLayers.HeadSide && IsEar(entry.Prototype),
            MarkingFilter.Horns => IsHorn(entry.Prototype),
            _ => true,
        };
    }

    private bool IsHeadOnlyFilter(MarkingFilter filter)
    {
        return filter switch
        {
            MarkingFilter.Face or MarkingFilter.Eyes or MarkingFilter.UpperEars or MarkingFilter.LowerEars or MarkingFilter.Horns => true,
            _ => false,
        };
    }

    private string GetFilterLabel(MarkingPrototype prototype)
    {
        if (IsScar(prototype))
            return "Шрамы";
        if (IsBandage(prototype))
            return "Повязки";
        return "Особые";
    }

    private bool IsScar(MarkingPrototype prototype)
    {
        var name = GetMarkingName(prototype);
        return prototype.ID.Contains("Scar", StringComparison.OrdinalIgnoreCase) ||
               name.Contains("шрам", StringComparison.OrdinalIgnoreCase);
    }

    private bool IsBandage(MarkingPrototype prototype)
    {
        var name = GetMarkingName(prototype);
        return prototype.ID.Contains("Gauze", StringComparison.OrdinalIgnoreCase) ||
               prototype.ID.Contains("Bandage", StringComparison.OrdinalIgnoreCase) ||
               name.Contains("бинт", StringComparison.OrdinalIgnoreCase) ||
               name.Contains("повяз", StringComparison.OrdinalIgnoreCase);
    }

    private bool IsEar(MarkingPrototype prototype)
    {
        var name = GetMarkingName(prototype);
        return prototype.ID.Contains("Ear", StringComparison.OrdinalIgnoreCase) ||
               prototype.ID.Contains("Bunny", StringComparison.OrdinalIgnoreCase) ||
               prototype.ID.Contains("Rabbit", StringComparison.OrdinalIgnoreCase) ||
               prototype.ID.Contains("Hare", StringComparison.OrdinalIgnoreCase) ||
               name.Contains("ух", StringComparison.OrdinalIgnoreCase) ||
               name.Contains("ear", StringComparison.OrdinalIgnoreCase);
    }

    private bool IsHorn(MarkingPrototype prototype)
    {
        var name = GetMarkingName(prototype);
        return prototype.ID.Contains("Horn", StringComparison.OrdinalIgnoreCase) ||
               name.Contains("рог", StringComparison.OrdinalIgnoreCase) ||
               name.Contains("horn", StringComparison.OrdinalIgnoreCase);
    }

    private string GetMarkingName(MarkingPrototype prototype)
    {
        return Loc.TryGetString($"marking-{prototype.ID}", out var name)
            ? name
            : prototype.ID;
    }

    private string GetLayerName(HumanoidVisualLayers layer)
    {
        return Loc.TryGetString($"markings-layer-{layer}", out var name)
            ? name
            : layer.ToString();
    }

    private IEnumerable<string> GetSpeciesTags(MarkingPrototype prototype)
    {
        if (prototype.SpeciesRestriction is null)
            yield break;

        foreach (var species in prototype.SpeciesRestriction)
        {
            if (_prototype.TryIndex<SpeciesPrototype>(species, out var speciesPrototype))
                yield return Loc.GetString(speciesPrototype.Name);
            else
                yield return species.Id;
        }
    }

    private LayeredTextureRect CreatePreview(MarkingPrototype prototype, int size = 64)
    {
        return new LayeredTextureRect
        {
            Textures = prototype.Sprites.Select(layer => _sprite.Frame0(layer)).ToList(),
            TextureScale = new Vector2(2f, 2f),
            SetSize = new Vector2(size, size),
            VerticalAlignment = VAlignment.Center,
        };
    }

