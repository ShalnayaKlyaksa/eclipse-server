using Content.Client._Erida.Research.UI;
using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
namespace Content.Client.Research.UI;
[GenerateTypedNameReferences]
public sealed partial class ResearchClientServerSelectionMenu : FancyWindow
{
    public event Action<int>? OnServerSelected;
    public event Action? OnServerDeselected;
    public ResearchClientServerSelectionMenu()
    {
        RobustXamlLoader.Load(this);
        NetworkHint.SetMessage(Loc.GetString("research-terminal-select-network"), defaultColor: Color.FromHex("#A5C9AB"));
        ((Control)this).Stylesheet = ResearchTerminalTheme.Create(IoCManager.Resolve<IUserInterfaceManager>().Stylesheet);
    }
    public void Populate(int serverCount, string[] names, int[] ids, int selected)
    {
        Servers.RemoveAllChildren();
        for (var i = 0; i < Math.Min(serverCount, Math.Min(names.Length, ids.Length)); i++)
        {
            var id = ids[i];
            var active = selected == id;
            var button = new Button { Text = (active ? "[x] " : "[ ] ") + names[i] + $" · rd-{id}", ClipText = true, HorizontalExpand = true };
            button.OnPressed += _ => { if (active) OnServerDeselected?.Invoke(); else OnServerSelected?.Invoke(id); };
            Servers.AddChild(button);
        }
        ResearchTerminalTheme.StyleButtons(ContentsContainer);
    }
}
