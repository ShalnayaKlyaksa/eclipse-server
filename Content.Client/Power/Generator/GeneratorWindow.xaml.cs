using Content.Client.DoAfter;
using Content.Client._Erida.Research.UI;
using Content.Shared._Eclipse.Power;
using Robust.Client.UserInterface;
using Content.Client.UserInterface.Controls;
using Content.Shared.Power.Generator;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Network;

namespace Content.Client.Power.Generator;

[GenerateTypedNameReferences]
public sealed partial class GeneratorWindow : ImmersiveFancyWindow
{
    [Dependency] private readonly IEntityManager _entityManager = default!;
    [Dependency] private readonly ILocalizationManager _loc = default!;

    private EntityUid _entity;
    private int _fusionNominalKilowatts;

    public float? MaximumPower;

    public event Action<int>? OnPower;
    public event Action<bool>? OnState;
    public event Action? OnSwitchOutput;
    public event Action? OnEjectFuel;
    public event Action? OnReset;

    public GeneratorWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        ((Control) this).Stylesheet = ResearchTerminalTheme.Create(IoCManager.Resolve<IUserInterfaceManager>().Stylesheet);
        ResearchTerminalTheme.StyleButtons(ContentsContainer);
        ResetButton.OnPressed += _ => OnReset?.Invoke();
        FusionNominal.OnPressed += _ => OnPower?.Invoke(_fusionNominalKilowatts);
        FusionBoost.OnPressed += _ => OnPower?.Invoke((int) (MaximumPower.GetValueOrDefault() / 1000));

        TargetPower.InitDefaultButtons();
        TargetPower.IsValid += IsValid;
        TargetPower.ValueChanged += (args) =>
        {
            OnPower?.Invoke(args.Value);
        };

        StartButton.OnPressed += _ => OnState?.Invoke(true);
        StopButton.OnPressed += _ => OnState?.Invoke(false);
        OutputSwitchButton.OnPressed += _ => OnSwitchOutput?.Invoke();
        FuelEject.OnPressed += _ => OnEjectFuel?.Invoke();
    }

    public void SetEntity(EntityUid entity)
    {
        _entity = entity;
        EntityView.SetEntity(entity);
        PlantName.Text = _entityManager.GetComponent<MetaDataComponent>(entity).EntityName;
    }

    private bool IsValid(int arg)
    {
        if (arg < 0)
            return false;

        if (arg > (MaximumPower / 1000.0f ?? 0))
            return false;

        return true;
    }

    public void Update(PortableGeneratorComponentBuiState state)
    {
        MaximumPower = state.MaximumPower;
        OperatingPanel.Visible = state.Operating != null;
        var fusion = state.Operating?.FusionNominalPower != null;
        FusionModes.Visible = fusion;
        TargetPower.Visible = !fusion;
        EntityView.Scale = fusion ? new(1, 1) : new(2, 2);
        if (state.Operating is { } operating)
        {
            OperatingCondition.Text = Loc.GetString("power-plant-condition-" + operating.Condition.ToString().ToLowerInvariant());
            TargetLabel.Text = Loc.GetString(operating.GravitySource ? "power-plant-gravity-target" :
                operating.HeatSource ? "power-plant-thermal-target" : "portable-generator-ui-target-power-label");
            OperatingOutput.Text = Loc.GetString(operating.GravitySource ? "power-plant-gravity-output" :
                operating.HeatSource ? "power-plant-thermal-output" : "power-plant-electric-output",
                ("power", (int) ((operating.GravitySource ? operating.GravityPower :
                    operating.HeatSource ? operating.GeneratedHeatPower : operating.AvailablePower) / 1000)));
            OperatingTemperature.Text = Loc.GetString("power-plant-temperature", ("temperature", (int) operating.Temperature), ("limit", (int) operating.ShutdownTemperature));
            TemperatureBar.Value = Math.Clamp(operating.Temperature / MathF.Max(1, operating.ShutdownTemperature), 0, 1);
            OperatingCooling.Text = Loc.GetString("power-plant-cooling", ("power", (int) (operating.CoolingPower / 1000)));
            OperatingDecay.Visible = operating.HeatSource;
            OperatingDecay.Text = Loc.GetString("power-plant-decay", ("power", (int) (operating.DecayPower / 1000)));
            OperatingFields.Visible = operating.RequiredFields > 0;
            OperatingFields.Text = Loc.GetString("power-plant-fields", ("count", operating.FieldCount), ("required", operating.RequiredFields));
            OperatingKinetics.Visible = operating.GravitySource;
            OperatingKinetics.Text = Loc.GetString("power-plant-kinetics", ("count", operating.KineticGenerators),
                ("power", (int) (operating.HarvestedPower / 1000)));
            OperatingGravityHorizon.Visible = operating.GravitySource;
            if (operating.GravitySource)
                OperatingGravityHorizon.Text = Loc.GetString("gravity-plant-horizon",
                    ("radius", MathF.Round(operating.GravityHorizon, 1)), ("limit", MathF.Round(operating.GravityFieldLimit, 1)),
                    ("projectors", operating.GravityStaticProjectors));
            FusionUtilities.Visible = fusion;
            if (operating.FusionNominalPower is { } nominal)
            {
                Title = Loc.GetString("power-fusion-title");
                _fusionNominalKilowatts = (int) (nominal / 1000);
                FusionNominal.Disabled = state.TargetPower <= nominal;
                FusionBoost.Disabled = state.TargetPower >= state.MaximumPower;
                TargetLabel.Text = Loc.GetString("power-fusion-mode");
                OperatingOutput.Text = Loc.GetString("power-fusion-output",
                    ("delivered", (int) (operating.DeliveredPower / 1000)),
                    ("available", (int) (operating.AvailablePower / 1000)));
                FusionUtilities.Text = Loc.GetString("power-fusion-utilities",
                    ("power", (int) (operating.AuxiliaryPower / 1000)),
                    ("flow", (int) operating.CoolantFlow),
                    ("net", (int) ((operating.DeliveredPower - operating.AuxiliaryPower) / 1000)));
            }
            WarmupBar.Visible = state.On && operating.Warmup < 1;
            WarmupBar.Value = operating.Warmup;
            ResetButton.Visible = operating.Tripped && operating.Condition != PowerPlantCondition.Failed;
        }

        if (!_entityManager.TryGetComponent(_entity, out FuelGeneratorComponent? component))
            return;

        if (!TargetPower.LineEditControl.HasKeyboardFocus())
            TargetPower.OverrideValue((int)(state.TargetPower / 1000.0f));
        var efficiency = SharedGeneratorSystem.CalcFuelEfficiency(state.TargetPower, state.OptimalPower, component);
        Efficiency.Text = efficiency.ToString("P1");

        var burnRate = component.OptimalBurnRate / efficiency;
        var left = state.RemainingFuel / burnRate;

        Eta.Text = Loc.GetString(
            "portable-generator-ui-eta",
            ("minutes", Math.Ceiling(left / 60.0)));
        FuelFraction.Value = fusion ? Math.Clamp(state.RemainingFuel, 0, 1) : state.RemainingFuel - (int) state.RemainingFuel;
        FuelLeft.Text = fusion ? FuelFraction.Value.ToString("P0") : ((int) MathF.Floor(state.RemainingFuel)).ToString();
        FuelEject.Visible = state.CanEjectFuel;
        FuelEject.Disabled = fusion && state.RemainingFuel < 1;
        StartButton.Disabled = state.RemainingFuel <= 0 || state.Operating is { Tripped: true } ||
            state.Operating is { } plant && (plant.FieldCount < plant.RequiredFields || fusion && !plant.FusionReady);

        var progress = 0f;

        var unanchored = !_entityManager.GetComponent<TransformComponent>(_entity).Anchored;
        var starting = !unanchored && TryGetStartProgress(out progress);
        var on = !unanchored && !starting && state.On;
        var off = !unanchored && !starting && !state.On;

        LabelUnanchored.Visible = unanchored;
        StartProgress.Visible = starting;
        StopButton.Visible = on;
        StartButton.Visible = off;

        if (starting)
        {
            StatusLabel.Text = _loc.GetString("portable-generator-ui-status-starting");
            StatusLabel.SetOnlyStyleClass("negative");

            StartProgress.Value = progress;
        }
        else if (on)
        {
            StatusLabel.Text = _loc.GetString("portable-generator-ui-status-running");
            StatusLabel.SetOnlyStyleClass("positive");
        }
        else
        {
            StatusLabel.Text = _loc.GetString("portable-generator-ui-status-stopped");
            StatusLabel.SetOnlyStyleClass("highlight");
        }

        var canSwitch = _entityManager.TryGetComponent(_entity, out PowerSwitchableComponent? switchable) && state.Operating?.GravitySource != true;
        var switcher = _entityManager.System<SharedPowerSwitchableSystem>();
        VoltageRow.Visible = canSwitch;

        if (switchable != null)
        {
            var voltage = switcher.VoltageString(switcher.GetVoltage(_entity, switchable));
            OutputSwitchLabel.Text = Loc.GetString("portable-generator-ui-current-output", ("voltage", voltage));
            var nextVoltage = switcher.VoltageString(switcher.GetNextVoltage(_entity, switchable));
            OutputSwitchButton.Text = Loc.GetString("power-switchable-switch-voltage", ("voltage", nextVoltage));
            OutputSwitchButton.Disabled = state.On;
        }

        CloggedLabel.Visible = state.Clogged;

        if (state.Operating?.GravitySource == true)
        {
            NetworkStats.Text = Loc.GetString("power-plant-gravity-network");
            NetworkStats.StyleClasses.Clear();
        }
        else if (state.NetworkStats is { } netStats)
        {
            NetworkStats.Text = Loc.GetString(
                "portable-generator-ui-network-stats-value",
                ("load", netStats.Load),
                ("supply", netStats.Supply));

            var good = netStats.Load <= netStats.Supply;
            NetworkStats.SetOnlyStyleClass(good ? "positive" : "highlight");
        }
        else
        {
            NetworkStats.Text = Loc.GetString("portable-generator-ui-network-stats-not-connected");
            NetworkStats.StyleClasses.Clear();
        }
    }

    private bool TryGetStartProgress(out float progress)
    {
        // Try to check progress of auto-revving first
        if (_entityManager.TryGetComponent<ActiveGeneratorRevvingComponent>(_entity, out var activeGeneratorRevvingComponent) && _entityManager.TryGetComponent<PortableGeneratorComponent>(_entity, out var portableGeneratorComponent))
        {
            var calculatedProgress = activeGeneratorRevvingComponent.CurrentTime / portableGeneratorComponent.StartTime;
            progress = (float) calculatedProgress;
            return true;
        }

        var doAfterSystem = _entityManager.EntitySysManager.GetEntitySystem<DoAfterSystem>();
        return doAfterSystem.TryFindActiveDoAfter<GeneratorStartedEvent>(_entity, out _, out _, out progress);
    }
}
