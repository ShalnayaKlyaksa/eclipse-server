using Content.Client.Stylesheets;
using Content.Shared.Traits;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;
using Robust.Shared.Utility;

namespace Content.Client.Lobby.UI.Roles;

[GenerateTypedNameReferences]
public sealed partial class TraitPreferenceSelector : Control
{
    private string? _description;

    public bool Preference
    {
        get => Checkbox.Pressed;
        set => Checkbox.Pressed = value;
    }

    public bool Disabled
    {
        get => Checkbox.Disabled;
        set => Checkbox.Disabled = value;
    }

    public event Action<bool>? PreferenceChanged;

    public TraitPreferenceSelector(TraitPrototype trait)
    {
        RobustXamlLoader.Load(this);

        var cost = trait.Cost;
        Checkbox.Text = Loc.GetString(trait.Name);
        // Clipped labels measure to zero width, so give the title the space left by the icon.
        Checkbox.Label.HorizontalExpand = true;
        PointCost.Text = cost.ToString("+#;-#;0");
        PointCost.FontColorOverride = cost > 0 ? Color.LightGreen : cost < 0 ? ForgeStyle.Accent : ForgeStyle.Muted;
        Card.PanelOverride = ForgeStyle.Panel(ForgeStyle.Surface, ForgeStyle.Border);
        Checkbox.OnToggled += OnCheckBoxToggled;

        if (trait.Description is { } desc)
        {
            _description = Loc.GetString(desc);
            Description.SetMessage(FormattedMessage.FromUnformatted(_description), ForgeStyle.Muted);
            Checkbox.ToolTip = _description;
        }
    }

    public void SetBlockReason(string? reason)
    {
        Disabled = reason != null;
        Checkbox.Label.FontColorOverride = reason != null ? Color.Gray : null;
        BlockReason.Visible = reason != null;
        if (reason != null)
            BlockReason.SetMessage(FormattedMessage.FromUnformatted(reason), ForgeStyle.Accent);
        Checkbox.ToolTip = reason == null
            ? _description
            : _description == null
                ? reason
                : $"{_description}\n{reason}";
    }

    private void OnCheckBoxToggled(BaseButton.ButtonToggledEventArgs args)
    {
        PreferenceChanged?.Invoke(Preference);
    }
}
