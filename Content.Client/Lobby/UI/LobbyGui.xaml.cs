        private void UpdateLaunchStatusAnimation(float deltaSeconds)
        {
            var target = _launchStatusTargetVisible ? 1f : 0f;
            _launchStatusVisibility = Math.Clamp(
                _launchStatusVisibility + MathF.Sign(target - _launchStatusVisibility) * deltaSeconds * LaunchStatusAnimationSpeed,
                0f,
                1f);

            if (MathF.Abs(_launchStatusVisibility - target) < 0.001f)
                _launchStatusVisibility = target;

            // Once the block has fully faded (round started) it stops reserving space entirely, so the panel can
            // end right after the currencies with no empty gap. ApplyTopStatusLayout owns that, since it also has
            // to drop the block when the window is too narrow for it.
        }

        private void ApplyEclipseLayout()
        {
            var width = MathF.Max(MainContainer.Width, 1f);
            var height = MathF.Max(MainContainer.Height, 1f);

            // Single horizontal shrink factor: 0 at WideLayoutWidth and above, 1 at CompactLayoutWidth and below.
            var tWidth = Math.Clamp((WideLayoutWidth - width) / (WideLayoutWidth - CompactLayoutWidth), 0f, 1f);
            var sidebarWidth = Lerp(SidebarWidth, SidebarWidthCompact, tWidth);
            var rightGap = Lerp(EdgeGap, NarrowEdgeGap, tWidth);
            var centerGap = Lerp(WideCenterGap, CompactCenterGap, tWidth);
            var centerRightGap = Lerp(CenterRightGap, CompactCenterRightGap, tWidth);
            var centerLeft = sidebarWidth + centerGap;

            ApplySidebarLayout(height);

            // The right panel yields width to the centre column until it hits RightWidthMin, so the top status
            // panel can keep all of its blocks (including the round timer) for as long as the window allows.
            var minCenterWidth = AccountWidthSqueezed + centerRightGap;
            var rightWidth = Math.Clamp(width - rightGap - centerLeft - minCenterWidth, RightWidthMin, RightWidth);
            var rightStart = width - rightGap - rightWidth;

            // The centre column takes whatever space is left. Panels are capped to it (Math.Min) so they can
            // never overflow onto the right panel. The previous hard 640px minimum overlapped on <=1360px windows.
            var availableCenterWidth = MathF.Max(rightStart - centerLeft - centerRightGap, 1f);
            var accountWidth = ApplyTopStatusLayout(availableCenterWidth);
            var newsWidth = Math.Min(NewsWidth, availableCenterWidth);
            var showNews = availableCenterWidth >= MinNewsWidth && height >= MinNewsHeightWindow;

            // The votes / rules buttons sit beside an expanding panel, so they shrink with the right column.
            var sideButtonWidth = Lerp(SideButtonWidth, SideButtonWidthCompact, tWidth);
            VotesTabButton.SetWidth = sideButtonWidth;
            RulesButton.SetWidth = sideButtonWidth;

            SetLeftStretch(LeftSide, 0f, sidebarWidth);
            // Override the XAML SetSize minimum so the panels can actually shrink (e.g. the top panel
            // to its compact width once the launch/timer block is gone) instead of being pinned wide.
            TopStatusPanel.SetWidth = accountWidth;
            NewsPanel.SetWidth = newsWidth;
            SetTopLeft(TopStatusPanel, centerLeft, TopGap, accountWidth, AccountHeight);
            SetBottomLeft(NewsPanel, centerLeft, NewsBottomGap, newsWidth, NewsHeight);
            NewsPanel.Visible = showNews && DefaultState.Visible && _section == LobbySection.Play;
            SetTopRight(ServerActions, rightGap, TopGap, rightWidth, ServerActionsHeight);
            // Dropdown hangs directly under the server button, matching the right column's width.
            var serverListHeight = Servers.Length * ServerRowHeight + ServerListPadding;
            SetTopRight(ServerListPanel, rightGap, TopGap + ServerActionsHeight + 4f, rightWidth, serverListHeight);
            SetRightStretch(RightSide, rightGap, RightPanelTop, rightWidth, RightPanelBottomGap);
            SetTopRight(ExpandPanel, rightGap, RightPanelTop, 44f, 44f);
            SetBottomRight(BottomActions, rightGap, BottomGap, rightWidth, BottomActionsHeight);
            var voteCount = VoteContainer.ChildCount;
            var voteHeight = voteCount == 0
                ? VotePopupHeight
                : voteCount * VotePopupHeight + (voteCount - 1) * VotePopupSpacing;
            SetTopLeft(VoteContainer, centerLeft, TopGap + AccountHeight + 12f, Math.Min(accountWidth, 640f), voteHeight);
            var characterSetupActive = CharacterSetupState.Visible;
            if (characterSetupActive)
            {
                var showSecondaryLobbyPanels = width >= CharacterSetupNarrowBreakpoint;
                ServerActions.Visible = showSecondaryLobbyPanels;
                RightSide.Visible = showSecondaryLobbyPanels;
                BottomActions.Visible = showSecondaryLobbyPanels;
            }

            // Never leave the dropdown floating when its button is gone.
            if (!ServerActions.Visible)
                SetServerListOpen(false);

            var reserveRightPanel = RightSide.Visible && (!characterSetupActive || width >= CharacterSetupNarrowBreakpoint);
            var centerRightReserve = reserveRightPanel ? rightGap + rightWidth + 28f : rightGap;
            SetTopLeft(SectionPanel, sidebarWidth, 0f, MathF.Max(width - sidebarWidth - centerRightReserve, 1f), height);

            var setupLeft = width < NarrowBreakpoint ? rightGap : sidebarWidth + 28f;
            var setupTop = width < NarrowBreakpoint ? rightGap : TopGap;
            var setupBottomGap = width < NarrowBreakpoint ? rightGap : BottomGap;
            var setupWidth = MathF.Max(width - setupLeft - centerRightReserve, CharacterSetupMinimumWidth);
            var setupHeight = MathF.Max(height - setupTop - setupBottomGap, 1f);
            SetTopLeft(CharacterSetupState, setupLeft, setupTop, setupWidth, setupHeight);
        }

        /// <summary>
        /// Fits the top status panel into <paramref name="availableWidth"/> and returns the width it ended up with.
        /// Its blocks squeeze down to <see cref="AccountBlockScaleMin"/> first; only if that still does not fit is
        /// the launch/timer block dropped, which is also what happens on its own once the round starts.
        /// </summary>
        private float ApplyTopStatusLayout(float availableWidth)
        {
            if (MathHelper.CloseToPercent(availableWidth, _topStatusLayoutWidth)
                && MathHelper.CloseTo(_launchStatusVisibility, _topStatusLayoutVisibility))
            {
                return _topStatusWidth;
            }

            _topStatusLayoutWidth = availableWidth;
            _topStatusLayoutVisibility = _launchStatusVisibility;

            // The timer only stays if it fits alongside fully squeezed blocks; otherwise its width goes back to them.
            var visibility = availableWidth >= AccountWidthSqueezed ? _launchStatusVisibility : 0f;
            var showLaunch = visibility > 0.001f;

            LaunchStatus.Visible = showLaunch;
            LaunchStatus.ReservesSpace = showLaunch;
            LaunchDivider.Visible = showLaunch;
            LaunchDivider.ReservesSpace = showLaunch;
            LaunchStatus.Modulate = Color.White.WithAlpha(visibility);
            LaunchDivider.Modulate = Color.White.WithAlpha(visibility);

            // Solved from availableWidth = fixed + launch chrome + (blocks + launch block) * scale, so the blocks
            // take exactly the space that is there rather than an approximation of it.
            var scale = Math.Clamp(
                (availableWidth - AccountFixedWidth - LaunchStatusChromeWidth * visibility)
                / (AccountBlocksWidth + LaunchStatusWidth * visibility),
                AccountBlockScaleMin,
                1f);

            AccountNameBlock.SetWidth = AccountNameWidth * scale;
            AccountRankBlock.SetWidth = AccountRankWidth * scale;
            AccountCurrencyBlock.SetWidth = AccountCurrencyWidth * scale;
            LaunchStatus.SetWidth = LaunchStatusWidth * scale;

            var designWidth = AccountFixedWidth + AccountBlocksWidth * scale
                              + (LaunchStatusWidth * scale + LaunchStatusChromeWidth) * visibility;
            _topStatusWidth = Math.Min(designWidth, availableWidth);
            return _topStatusWidth;
        }

        /// <summary>
        /// Total height the sidebar column wants at shrink factor <paramref name="t"/>, where 0 is every row at its
        /// natural height and 1 is every row at its minimum. Linear in <paramref name="t"/>, which is what lets
        /// <see cref="ApplySidebarLayout"/> solve for the factor that exactly fills the panel.
        /// </summary>
        private static float SidebarColumnHeight(float t, float previewMin)
        {
            return Lerp(SidebarHeaderNatural, SidebarHeaderMin, t)
                   + Lerp(SidebarHeaderGapNatural, SidebarHeaderGapMin, t)
                   + Lerp(NavPrimaryNatural, NavPrimaryMin, t)
                   + NavGapCount * Lerp(NavGapNatural, NavGapMin, t)
                   + NavButtonCount * Lerp(NavNatural, NavMin, t)
                   + SiteGapCount * Lerp(SiteGapNatural, SiteGapMin, t)
                   + Lerp(PreviewNatural, previewMin, t)
                   + Lerp(PreviewGapNatural, PreviewGapMin, t)
                   + Lerp(LeaveNatural, LeaveMin, t)
                   + Lerp(SidebarMarginTopNatural, SidebarMarginTopMin, t)
                   + Lerp(SidebarMarginBottomNatural, SidebarMarginBottomMin, t);
        }

        private void ApplySidebarLayout(float panelHeight)
        {
            if (MathHelper.CloseToPercent(panelHeight, _sidebarLayoutHeight))
                return;

            _sidebarLayoutHeight = panelHeight;

            var height = panelHeight - SidebarFitSlack;
            var natural = SidebarColumnHeight(0f, PreviewMin);

            // Give up the preview's sprite viewport only if keeping it would not fit even fully shrunk.
            var previewMin = PreviewMin;
            var minimum = SidebarColumnHeight(1f, previewMin);
            if (height < minimum)
            {
                previewMin = PreviewMinNoViewport;
                minimum = SidebarColumnHeight(1f, previewMin);
            }

            var t = natural <= minimum
                ? 0f
                : Math.Clamp((natural - height) / (natural - minimum), 0f, 1f);

            var headerHeight = Lerp(SidebarHeaderNatural, SidebarHeaderMin, t);
            var logoSize = Lerp(SidebarLogoIconNatural, SidebarLogoIconMin, t);
            var navGap = Lerp(NavGapNatural, NavGapMin, t);
            var navHeight = Lerp(NavNatural, NavMin, t);
            var previewHeight = Lerp(PreviewNatural, previewMin, t);

            SidebarColumn.Margin = new Thickness(
                32f,
                Lerp(SidebarMarginTopNatural, SidebarMarginTopMin, t),
                24f,
                Lerp(SidebarMarginBottomNatural, SidebarMarginBottomMin, t));

            SidebarHeader.SetHeight = headerHeight;
            SidebarLogoIcon.SetSize = new Vector2(logoSize, logoSize);
            SidebarHeaderGap.SetHeight = Lerp(SidebarHeaderGapNatural, SidebarHeaderGapMin, t);

            SetNavButtonHeight(PlaySectionButton, Lerp(NavPrimaryNatural, NavPrimaryMin, t));
            SetNavButtonHeight(StoreSectionButton, navHeight);
            SetNavButtonHeight(AccountSectionButton, navHeight);
            SetNavButtonHeight(SettingsSectionButton, navHeight);
            SetNavButtonHeight(RoadmapSectionButton, navHeight);
            SetNavButtonHeight(TutorialSectionButton, navHeight);
            SetNavButtonHeight(SiteButton, navHeight);
            SetNavButtonHeight(LeaveButton, Lerp(LeaveNatural, LeaveMin, t));

            NavGap1.SetHeight = navGap;
            NavGap2.SetHeight = navGap;
            NavGap3.SetHeight = navGap;
            NavGap4.SetHeight = navGap;
            NavGap5.SetHeight = navGap;
            var siteGap = Lerp(SiteGapNatural, SiteGapMin, t);
            SiteGapTop.SetHeight = siteGap;
            SiteGap.SetHeight = siteGap;
            PreviewGap.SetHeight = Lerp(PreviewGapNatural, PreviewGapMin, t);

            CharacterPreview.SetHeight = previewHeight;
            CharacterPreview.ApplyHeight(previewHeight);

            // Two lines of text no longer fit once the buttons get short, so the subtitles are dropped first.
            var showSubtitles = navHeight >= NavSubtitleMinHeight;
            SetSubtitleVisible(PlaySectionSubtitle, showSubtitles);
            SetSubtitleVisible(StoreSectionSubtitle, showSubtitles);
            SetSubtitleVisible(AccountSectionSubtitle, showSubtitles);
            SetSubtitleVisible(SettingsSectionSubtitle, showSubtitles);
            SetSubtitleVisible(RoadmapSectionSubtitle, showSubtitles);
            SetSubtitleVisible(TutorialSectionSubtitle, showSubtitles);
            SetSubtitleVisible(SiteButtonSubtitle, showSubtitles);
            SetSubtitleVisible(LeaveButtonSubtitle, showSubtitles);
        }

        /// <summary>
        /// Pins a nav button to an exact height. MinSize wins over SetSize in <see cref="Control.Measure"/>,
        /// so both have to be set for the button to be able to shrink below its XAML height.
        /// </summary>
        private static void SetNavButtonHeight(Button button, float height)
        {
            button.MinHeight = height;
            button.SetHeight = height;
        }

        private static void SetSubtitleVisible(Label subtitle, bool visible)
        {
            subtitle.Visible = visible;
            subtitle.ReservesSpace = visible;
        }

        private static float Lerp(float natural, float minimum, float t)
        {
            return natural + (minimum - natural) * t;
        }

        private static void SetTopLeft(Control control, float left, float top, float width, float height)
        {
            LayoutContainer.SetAnchorLeft(control, 0f);
            LayoutContainer.SetAnchorTop(control, 0f);
            LayoutContainer.SetAnchorRight(control, 0f);
            LayoutContainer.SetAnchorBottom(control, 0f);
            LayoutContainer.SetMarginLeft(control, left);
            LayoutContainer.SetMarginTop(control, top);
            LayoutContainer.SetMarginRight(control, left + width);
            LayoutContainer.SetMarginBottom(control, top + height);
            LayoutContainer.SetGrowHorizontal(control, LayoutContainer.GrowDirection.Constrain);
            LayoutContainer.SetGrowVertical(control, LayoutContainer.GrowDirection.Constrain);
        }

