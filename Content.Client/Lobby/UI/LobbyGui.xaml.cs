        private void BuildRoadmap()
        {
            RoadmapEntries.RemoveAllChildren();

            for (var i = 0; i < _roadmapEntries.Length; i++)
            {
                RoadmapEntries.AddChild(BuildRoadmapEntry(_roadmapEntries[i], i + 1));
            }

            var done = _roadmapEntries.Count(entry => entry.Completed);
            var total = Math.Max(1, _roadmapEntries.Length);
            var fraction = (float) done / total;

            RoadmapProgressLabel.Text = $"Выполнено {done} из {_roadmapEntries.Length}";
            RoadmapProgressPercent.Text = $"{MathF.Round(fraction * 100f)}%";
            RoadmapProgressBar.Value = fraction;
        }

