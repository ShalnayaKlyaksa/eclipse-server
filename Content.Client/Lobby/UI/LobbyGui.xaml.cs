        /// <summary>
        /// Fills the account page. Called whenever the account card refreshes, so the page is current whenever
        /// the player opens it.
        /// </summary>
        public void SetAccountPageData(AccountPageData data)
        {
            AccountPageName.Text = data.AccountName;
            AccountPageRank.Text = data.RankName;
            AccountPageLevel.Text = $"Ур. {data.Level}";
            AccountPageXpBar.Value = data.NextLevelExperience <= 0
                ? 1f
                : Math.Clamp((float) data.CurrentExperience / data.NextLevelExperience, 0f, 1f);
            AccountPageXpText.Text = data.Level >= EclipseProgression.MaxLevel
                ? "Максимальный уровень"
                : $"{FormatAmount(data.CurrentExperience)} / {FormatAmount(data.NextLevelExperience)} XP" +
                  $"  ·  до следующего уровня {FormatAmount(Math.Max(0, data.NextLevelExperience - data.CurrentExperience))}";

            // This runs once a second from the account card refresh, so the card lists are only rebuilt when
            // something they show actually changed.
            var signature = HashCode.Combine(
                data.Level,
                data.Merits,
                data.Shards,
                (int) data.TotalPlaytime.TotalMinutes,
                data.TopRoles.Count,
                data.Achievements.Count,
                data.Achievements.Count(achievement => achievement.Completed));

            if (signature == _accountPageSignature)
                return;

            _accountPageSignature = signature;
            BuildAccountStats(data);
            BuildAccountRoles(data.TopRoles);
            BuildAccountAchievements(data.Achievements);
        }

