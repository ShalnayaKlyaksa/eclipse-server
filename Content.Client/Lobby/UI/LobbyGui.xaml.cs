        private static Control BuildStat(string caption, string value, string? icon)
        {
            var column = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
                SeparationOverride = 4,
            };
            column.AddChild(new Label
            {
                Text = caption,
                StyleIdentifier = MainMenuControl.StyleIdentifierTinySubtle,
                ClipText = true,
            });

            var amount = new BoxContainer { SeparationOverride = 6 };
            if (icon != null)
            {
                amount.AddChild(new TextureRect
                {
                    TexturePath = icon,
                    SetSize = new Vector2(18),
                    Stretch = TextureRect.StretchMode.KeepAspectCentered,
                    VerticalAlignment = VAlignment.Center,
                });
            }
            amount.AddChild(new Label
            {
                Text = value,
                StyleIdentifier = MainMenuControl.StyleIdentifierScore,
                HorizontalExpand = true,
                ClipText = true,
            });
            column.AddChild(amount);

            return column;
        }

