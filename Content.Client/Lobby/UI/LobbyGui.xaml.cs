        /// <summary>
        /// Hosts the player's ahelp chat inside the admins tab up front (non-admins only), so a message from an
        /// admin lands in the tab instead of popping the old window. Admins keep the full bwoink window.
        /// </summary>
        private void EnsureEmbeddedAdminChat()
        {
            if (_adminManager.HasFlag(AdminFlags.Adminhelp) || AdminsChatContainer.ChildCount > 0)
                return;

            if (UserInterfaceManager.GetUIController<AHelpUIController>().GetEmbeddedPlayerChat() is { } panel)
                AdminsChatContainer.AddChild(panel);
        }

        protected override void ExitedTree()
        {
            _voteManager.CanCallVoteChanged -= UpdateVotesTab;

            if (_voteCallMenu is { IsOpen: true })
                _voteCallMenu.Close();

            // Never leave the manifest redirect installed once the lobby is gone.
            CrewManifestEui.LobbyManifestSink = null;
            // Hand the ahelp panel back so in-game ahelp uses its normal window.
            UserInterfaceManager.GetUIController<AHelpUIController>().ReleaseEmbeddedPlayerChat();

            base.ExitedTree();
        }

