            if (!string.IsNullOrWhiteSpace(achievement.Icon))
            {
                iconWrap.AddChild(new TextureRect
                {
                    TexturePath = achievement.Icon,
                    Stretch = TextureRect.StretchMode.KeepAspectCentered,
                    // Locked achievements are greyed out so finished ones stand out.
                    ModulateSelfOverride = accent,
                    HorizontalExpand = true,
                    VerticalExpand = true,
                });
            }
            row.AddChild(iconWrap);

            var column = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Center,
                SeparationOverride = 4,
            };
            row.AddChild(column);

            var titleRow = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                SeparationOverride = 6,
            };
            titleRow.AddChild(new Label
            {
                Text = achievement.Name,
                StyleIdentifier = MainMenuControl.StyleIdentifierCompactText,
                ModulateSelfOverride = completed ? Color.FromHex("#F0A513") : null,
                HorizontalExpand = true,
                ClipText = true,
            });
            if (completed)
            {
                titleRow.AddChild(new Label
                {
                    Text = "✓",
                    StyleIdentifier = MainMenuControl.StyleIdentifierGoldSmall,
                    VerticalAlignment = VAlignment.Center,
                });
            }
            column.AddChild(titleRow);

            var description = new RichTextLabel { HorizontalExpand = true };
            description.SetMessage(achievement.Description, Color.FromHex("#9A9A9A"));
            column.AddChild(description);

            if (!completed)
            {
                column.AddChild(new ProgressBar
                {
                    MinValue = 0f,
                    MaxValue = 1f,
                    Value = achievement.Fraction,
                    SetHeight = 6f,
                    HorizontalExpand = true,
                });
                column.AddChild(new Label
                {
                    Text = $"{FormatGoal(achievement.Current)} / {FormatGoal(achievement.Goal)}",
                    StyleIdentifier = MainMenuControl.StyleIdentifierTinySubtle,
                });
            }

            return card;
        }

        private static string FormatGoal(float value)
        {
            return value >= 10f || MathF.Abs(value - MathF.Round(value)) < 0.05f
                ? MathF.Round(value).ToString("0", CultureInfo.InvariantCulture)
                : value.ToString("0.#", CultureInfo.InvariantCulture);
        }

        private static string FormatPlaytime(TimeSpan time)
        {
            var hours = (int) time.TotalHours;
            return hours >= 1
                ? $"{hours} ч {time.Minutes} мин"
                : $"{time.Minutes} мин";
        }

