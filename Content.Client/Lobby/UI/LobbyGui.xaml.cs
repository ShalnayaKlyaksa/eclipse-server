        /// <summary>
        /// Pushes the current entry's text and image into the card and refreshes the position dots.
        /// </summary>
        private void ApplyCurrentNews()
        {
            // No news prototypes loaded: keep the panel usable instead of showing the XAML placeholder text.
            if (_news.Length == 0)
            {
                NewsDate.Text = string.Empty;
                NewsTitle.Text = "Новостей пока нет";
                NewsText.Text = string.Empty;
                NewsCard.Disabled = true;
                return;
            }

            NewsCard.Disabled = false;

            var entry = _news[_newsIndex];
            NewsDate.Text = entry.Date;
            NewsTitle.Text = entry.Title;
            NewsText.Text = entry.Summary;

            NewsBadgeSlot.RemoveAllChildren();
            if (GetNewsBadge(entry.Badge) != null)
                NewsBadgeSlot.AddChild(BuildNewsBadge(entry.Badge));

            if (!string.IsNullOrWhiteSpace(entry.TexturePath))
                NewsImage.TexturePath = entry.TexturePath;

            for (var i = 0; i < NewsDots.ChildCount; i++)
            {
                if (NewsDots.GetChild(i) is PanelContainer dot && dot.PanelOverride is StyleBoxFlat box)
                    box.BackgroundColor = i == _newsIndex ? NewsDotActiveColor : NewsDotInactiveColor;
            }
        }

        /// <summary>
        /// Advances the news card: holds the current entry, then fades it out, swaps to the next, and fades back in.
        /// </summary>
        private void UpdateNewsCycle(float deltaSeconds)
        {
            if (_news.Length < 2)
                return;

            var step = deltaSeconds / NewsFadeSeconds;

            // Three explicit phases. Fading in has to be its own state: sharing it with "holding" made the hold
            // timer return early right after a swap, so the card stayed at alpha 0 and every entry after the
            // first was invisible.
            if (_newsFadingOut)
            {
                _newsFade -= step;
                if (_newsFade <= 0f)
                {
                    // Fully faded out: swap to the next entry, then start fading the new one back in.
                    _newsFade = 0f;
                    _newsFadingOut = false;
                    _newsFadingIn = true;
                    _newsIndex = (_newsIndex + 1) % _news.Length;
                    ApplyCurrentNews();
                }
            }
            else if (_newsFadingIn)
            {
                _newsFade += step;
                if (_newsFade >= 1f)
                {
                    _newsFade = 1f;
                    _newsFadingIn = false;
                }
            }
            else
            {
                _newsHoldTimer += deltaSeconds;
                if (_newsHoldTimer < NewsHoldSeconds)
                    return;

                _newsHoldTimer = 0f;
                _newsFadingOut = true;
            }

            NewsCardBody.Modulate = Color.White.WithAlpha(_newsFade);
        }

