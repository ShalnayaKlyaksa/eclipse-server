        private void ShowSection(LobbySection section)
        {
            _section = section;
            var play = section == LobbySection.Play;

            // The dropdown floats above everything, so it must not survive a section change.
            SetServerListOpen(false);

            TopStatusPanel.Visible = play;
            NewsPanel.Visible = play;
            ServerActions.Visible = true;
            RightSide.Visible = true;
            BottomActions.Visible = true;
            VoteContainer.Visible = play;
            SectionPanel.Visible = !play;
            var hasSectionHeader = section is not (LobbySection.Roadmap or LobbySection.Account or LobbySection.Site);
            SectionHeader.Visible = hasSectionHeader;
            SectionDivider.Visible = hasSectionHeader;
            StoreContent.Visible = false;
            StoreEmptyContent.Visible = section == LobbySection.Store;
            RoadmapContent.Visible = section == LobbySection.Roadmap;
            StoreHeaderBalances.Visible = false;

            var settings = section == LobbySection.Settings;
            SettingsContent.Visible = settings;
            if (settings)
                EnsureSettingsTabs();

            AccountContent.Visible = section == LobbySection.Account;

            SiteContent.Visible = section == LobbySection.Site;
            if (section == LobbySection.Site)
                EnsureSitePages();

            // Sections that fill the panel themselves get no placeholder text and no bottom filler.
            var fillsPanel = section is LobbySection.Store or LobbySection.Roadmap or LobbySection.Settings
                or LobbySection.Account or LobbySection.Site;
            SectionBody.Visible = !fillsPanel;
            SectionFiller.Visible = !fillsPanel;

            PlaySectionButton.StyleIdentifier = play ? MainMenuControl.StyleIdentifierPrimary : MainMenuControl.StyleIdentifierLobbyNav;
            StoreSectionButton.StyleIdentifier = section == LobbySection.Store ? MainMenuControl.StyleIdentifierPrimary : MainMenuControl.StyleIdentifierLobbyNav;
            AccountSectionButton.StyleIdentifier = section == LobbySection.Account ? MainMenuControl.StyleIdentifierPrimary : MainMenuControl.StyleIdentifierLobbyNav;
            SettingsSectionButton.StyleIdentifier = section == LobbySection.Settings ? MainMenuControl.StyleIdentifierPrimary : MainMenuControl.StyleIdentifierLobbyNav;
            RoadmapSectionButton.StyleIdentifier = section == LobbySection.Roadmap ? MainMenuControl.StyleIdentifierPrimary : MainMenuControl.StyleIdentifierLobbyNav;
            SetNavButtonVisual(PlaySectionIcon, PlaySectionTitle, PlaySectionSubtitle, play);
            SetNavButtonVisual(StoreSectionIcon, StoreSectionTitle, StoreSectionSubtitle, section == LobbySection.Store);
            SetNavButtonVisual(AccountSectionIcon, AccountSectionTitle, AccountSectionSubtitle, section == LobbySection.Account);
            SetNavButtonVisual(SettingsSectionIcon, SettingsSectionTitle, SettingsSectionSubtitle, section == LobbySection.Settings);
            SetNavButtonVisual(RoadmapSectionIcon, RoadmapSectionTitle, RoadmapSectionSubtitle, section == LobbySection.Roadmap);
            SiteButton.StyleIdentifier = section == LobbySection.Site ? MainMenuControl.StyleIdentifierPrimary : MainMenuControl.StyleIdentifierLobbyNav;
            SetNavButtonVisual(SiteButtonIcon, SiteButtonTitle, SiteButtonSubtitle, section == LobbySection.Site);
            SetNavButtonVisual(LeaveButtonIcon, LeaveButtonTitle, LeaveButtonSubtitle, false);


            switch (section)
            {
                case LobbySection.Play:
                    break;
                case LobbySection.Store:
                    if (_pdaCosmeticsStore == null)
                    {
                        _pdaCosmeticsStore = new Content.Client.PDA.PdaCosmeticsStoreControl();
                        StoreEmptyContent.AddChild(_pdaCosmeticsStore);
                    }
                    SectionIconTexture.TexturePath = "/Textures/Eclipse/MainMenu/icons/nav-store.png";
                    SectionTitle.Text = "МАГАЗИН";
                    SectionSubtitle.Text = Loc.GetString("pda-os-lobby-store-title");
                    break;
                case LobbySection.Account:
                    break;
                case LobbySection.Settings:
                    SectionIconTexture.TexturePath = "/Textures/Interface/VerbIcons/settings.svg.192dpi.png";
                    SectionTitle.Text = "НАСТРОЙКИ";
                    SectionSubtitle.Text = "Игра и интерфейс";
                    SectionBody.Text = "Здесь будет отдельный полноэкранный раздел настроек.";
                    break;
                case LobbySection.Roadmap:
                    SectionIconTexture.TexturePath = "/Textures/Eclipse/MainMenu/icons/nav-roadmap.png";
                    SectionTitle.Text = "ДОРОЖНАЯ КАРТА";
                    SectionSubtitle.Text = "Чего ожидать в будущих обновлениях";
                    break;
                case LobbySection.Site:
                    break;
                default:
                    throw new ArgumentOutOfRangeException(nameof(section), section, null);
            }

            ApplyEclipseLayout();
        }

        public void SwitchState(LobbyGuiState state)
        {
            DefaultState.Visible = false;
            CharacterSetupState.Visible = false;

            switch (state)
            {
                case LobbyGuiState.Default:
                    DefaultState.Visible = true;
                    ShowSection(_section);
                    break;
                case LobbyGuiState.CharacterSetup:
                    CharacterSetupState.Visible = true;
                    SectionPanel.Visible = false;
                    TopStatusPanel.Visible = false;
                    NewsPanel.Visible = false;
                    ServerActions.Visible = true;
                    RightSide.Visible = true;
                    BottomActions.Visible = true;
                    VoteContainer.Visible = false;

                    UserInterfaceManager.GetUIController<LobbyUIController>().ReloadCharacterSetup();

                    break;
            }

            ApplyEclipseLayout();
        }

