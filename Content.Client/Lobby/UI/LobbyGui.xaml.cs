        private void BuildAccountAchievements(IReadOnlyList<AccountAchievement> achievements)
        {
            AccountAchievements.RemoveAllChildren();

            var done = achievements.Count(a => a.Completed);
            AccountAchievementsCount.Text = $"Получено {done} из {achievements.Count}";

            foreach (var achievement in achievements)
                AccountAchievements.AddChild(BuildAchievementCard(achievement));
        }

        private static Control BuildAchievementCard(AccountAchievement achievement)
        {
            var card = new PanelContainer
            {
                HorizontalExpand = true,
                MinHeight = 116,
                PanelOverride = AccountCardStyle,
            };

            var row = new BoxContainer { SeparationOverride = 12 };
            card.AddChild(row);
            row.AddChild(new TextureRect
            {
                TexturePath = achievement.Icon,
                SetSize = new Vector2(28),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                VerticalAlignment = VAlignment.Top,
                ModulateSelfOverride = achievement.Completed ? Color.White : Color.FromHex("#A0A0A0"),
                Visible = !string.IsNullOrWhiteSpace(achievement.Icon),
            });

            var column = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
                SeparationOverride = 6,
            };
            row.AddChild(column);
            column.AddChild(new Label
            {
                Text = achievement.Name,
                StyleIdentifier = MainMenuControl.StyleIdentifierCompactText,
                ClipText = true,
            });

            var description = new RichTextLabel
            {
                MaxWidth = 272,
                HorizontalAlignment = HAlignment.Left,
            };
            description.SetMessage(achievement.Description, Color.FromHex("#BFBFBF"));
            column.AddChild(description);

            if (!achievement.Completed)
            {
                column.AddChild(new ProgressBar
                {
                    MinValue = 0f,
                    MaxValue = 1f,
                    Value = achievement.Fraction,
                    SetHeight = 4f,
                    BackgroundStyleBoxOverride = AccountProgressTrack,
                    ForegroundStyleBoxOverride = AchievementProgressFill,
                });
            }

            column.AddChild(new Label
            {
                Text = achievement.Completed
                    ? "Получено"
                    : $"{FormatGoal(achievement.Current)} / {FormatGoal(achievement.Goal)}",
                StyleIdentifier = MainMenuControl.StyleIdentifierTinySubtle,
                FontColorOverride = achievement.Completed ? NavActiveColor : null,
            });

            return card;
        }

        private static string FormatGoal(float value)
        {
            return value >= 10f || MathF.Abs(value - MathF.Round(value)) < 0.05f
                ? MathF.Round(value).ToString("0", CultureInfo.InvariantCulture)
                : value.ToString("0.#", CultureInfo.InvariantCulture);
        }

