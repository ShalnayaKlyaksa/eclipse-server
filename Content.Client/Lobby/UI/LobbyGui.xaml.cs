            };

            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                VerticalExpand = true,
                SeparationOverride = 10,
            };
            card.AddChild(row);

            if (icon != null)
            {
                row.AddChild(new TextureRect
                {
                    TexturePath = icon,
                    SetSize = new Vector2(28f, 28f),
                    Stretch = TextureRect.StretchMode.KeepAspectCentered,
                    VerticalAlignment = VAlignment.Center,
                });
            }

            var column = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Center,
                SeparationOverride = 2,
            };
            column.AddChild(new Label
            {
                Text = caption,
                StyleIdentifier = MainMenuControl.StyleIdentifierTinySubtle,
                ClipText = true,
            });
            column.AddChild(new Label
            {
                Text = value,
                StyleIdentifier = MainMenuControl.StyleIdentifierScore,
                ClipText = true,
            });
            row.AddChild(column);

            return card;
        }

        private void BuildAccountRoles(IReadOnlyList<(string Role, TimeSpan Time)> roles)
        {
            AccountTopRoles.RemoveAllChildren();

            if (roles.Count == 0)
            {
                AccountTopRoles.AddChild(new Label
                {
                    Text = "Пока нет отыгранных ролей.",
                    StyleIdentifier = MainMenuControl.StyleIdentifierSubtle,
                });
                return;
            }

            // Bars are relative to the most played role, so the comparison reads at a glance.
            var max = roles.Max(role => role.Time.TotalMinutes);

            foreach (var (role, time) in roles)
            {
                var row = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Horizontal,
                    HorizontalExpand = true,
                    SeparationOverride = 10,
                };
                row.AddChild(new Label
                {
                    Text = role,
                    StyleIdentifier = MainMenuControl.StyleIdentifierCompactText,
                    SetWidth = 190,
                    ClipText = true,
                    VerticalAlignment = VAlignment.Center,
                });
                row.AddChild(new ProgressBar
                {
                    MinValue = 0f,
                    MaxValue = 1f,
                    Value = max <= 0 ? 0f : (float) (time.TotalMinutes / max),
                    SetHeight = 8f,
                    HorizontalExpand = true,
                    VerticalAlignment = VAlignment.Center,
                });
                row.AddChild(new Label
                {
                    Text = FormatPlaytime(time),
                    StyleIdentifier = MainMenuControl.StyleIdentifierGoldSmall,
                    SetWidth = 68,
                    Align = Label.AlignMode.Right,
                    VerticalAlignment = VAlignment.Center,
                });
                AccountTopRoles.AddChild(row);
            }
        }

        private void BuildAccountAchievements(IReadOnlyList<AccountAchievement> achievements)
        {
            AccountAchievements.RemoveAllChildren();

            var done = achievements.Count(a => a.Completed);
