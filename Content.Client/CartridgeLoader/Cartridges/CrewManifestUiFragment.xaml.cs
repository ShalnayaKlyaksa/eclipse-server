using Content.Client.CrewManifest.UI;
using Content.Shared.CrewManifest;
using System.Linq;
using Content.Client.PDA;
using Content.Shared.Roles;
using Robust.Shared.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.CartridgeLoader.Cartridges;

[GenerateTypedNameReferences]
public sealed partial class CrewManifestUiFragment : BoxContainer
{
    private CrewManifestEntries? _entries;
    public CrewManifestUiFragment()
    {
        RobustXamlLoader.Load(this);

        StationName.AddStyleClass("pda-caption");
        Orientation = LayoutOrientation.Vertical;
        HorizontalExpand = true;
        VerticalExpand = true;
        SearchCrew.OnTextChanged += _ => BuildEntries();
    }

    public void UpdateState(string stationName, CrewManifestEntries? entries)
    {
        _entries = entries;

        StationNameContainer.Visible = entries != null;
        StationName.Text = stationName;

        BuildEntries();
    }
    private void BuildEntries()
    {
        CrewManifestListing.RemoveAllChildren();
        if (_entries == null) return;
        var entries = _entries.Entries.Where(entry => entry.Name.Contains(SearchCrew.Text, StringComparison.CurrentCultureIgnoreCase) || entry.JobTitle.Contains(SearchCrew.Text, StringComparison.CurrentCultureIgnoreCase)).ToArray();
        var prototypes = IoCManager.Resolve<IPrototypeManager>();
        var listed = new HashSet<CrewManifestEntry>();
        void Section(string title, CrewManifestEntry[] members)
        {
            if (members.Length == 0) return;
            CrewManifestListing.AddChild(new Label { Text = title + " · " + members.Length, Margin = new Thickness(2, 5, 2, 2), StyleClasses = { "pda-caption" } });
            CrewManifestListing.AddChild(new PanelContainer { MinHeight = 1, StyleClasses = { "pda-divider" } });
            foreach (var entry in members.OrderBy(entry => entry.Name))
            {
                var row = new BoxContainer { SeparationOverride = 5, Margin = new Thickness(3, 3), Children =
                {
                    new Label { Text = entry.Name, HorizontalExpand = true, ClipText = true, ToolTip = entry.Name },
                    new Label { Text = entry.JobTitle, SetWidth = 240, ClipText = true, ToolTip = entry.JobTitle, StyleClasses = { "terminal-muted" } },
                } };
                CrewManifestListing.AddChild(row); listed.Add(entry);
            }
        }
        foreach (var department in prototypes.EnumeratePrototypes<DepartmentPrototype>().OrderBy(dept => Loc.GetString(dept.Name)))
            Section(Loc.GetString(department.Name), entries.Where(entry => department.Roles.Contains(entry.JobPrototype)).ToArray());
        Section(Loc.GetString("pda-crew-other"), entries.Where(entry => !listed.Contains(entry)).ToArray());
        if (entries.Length == 0) CrewManifestListing.AddChild(new Label { Text = Loc.GetString("pda-crew-empty"), StyleClasses = { "terminal-muted" } });
    }
}
