using System.Linq;
using Content.Client.PDA;
using Content.Shared.CartridgeLoader.Cartridges;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Input;
using Robust.Shared.Utility;

namespace Content.Client.CartridgeLoader.Cartridges;

[GenerateTypedNameReferences]
public sealed partial class NotekeeperUiFragment : BoxContainer
{
    public event Action<NotekeeperUiMessageEvent>? OnAction;
    private sealed record Draft(string Title, string Body, int Revision, bool Dirty);
    private readonly Dictionary<Guid, Draft> _drafts = new();
    private NotekeeperEntry[] _entries = [];
    private Guid _selected;
    private Guid _pending;
    private Draft? _sent;
    private bool _new = true;
    private bool _dirty;
    private bool _loading;
    private bool _confirmDelete;
    private int _revision;
    private string Body => Rope.Collapse(Editor.TextRope);

    public NotekeeperUiFragment()
    {
        RobustXamlLoader.Load(this);
        Editor.StyleClasses.Add("pda-note-editor");
        NewNote.OnPressed += _ => Select(Guid.Empty);
        Search.OnTextChanged += _ => BuildList();
        NoteTitle.OnTextChanged += _ => Changed(); Editor.OnTextChanged += _ => Changed();
        Editor.OnKeyBindDown += args => { if (args.Function == EngineKeyFunctions.MultilineTextSubmit) { Save(); args.Handle(); } };
        SaveNote.OnPressed += _ => Save();
        ReloadNote.OnPressed += _ => { _drafts.Remove(_selected); Load(); };
        DeleteNote.OnPressed += _ =>
        {
            if (_new) return;
            if (!_confirmDelete) { _confirmDelete = true; DeleteNote.Text = Loc.GetString("pda-notes-confirm-delete"); return; }
            _pending = Guid.NewGuid(); _sent = null;
            OnAction?.Invoke(new(NotekeeperUiAction.Remove, "", id: _selected, revision: _revision, request: _pending));
        };
        Select(Guid.Empty);
    }
    private void SaveDraft() => _drafts[_selected] = new(NoteTitle.Text, Body, _revision, _dirty);
    private void Select(Guid id)
    {
        if (_pending != Guid.Empty) return;
        SaveDraft(); _selected = id; _new = id == Guid.Empty; _confirmDelete = false; Load(); BuildList();
    }
    private void Load()
    {
        _loading = true;
        var remote = _entries.FirstOrDefault(entry => entry.Id == _selected);
        var saved = _drafts.GetValueOrDefault(_selected);
        var draft = saved is { Dirty: true } ? saved : new Draft(remote?.Title ?? "", remote?.Body ?? "", remote?.Revision ?? 0, false);
        NoteTitle.Text = draft.Title; Editor.TextRope = Rope.Leaf.Empty; Editor.CursorPosition = new TextEdit.CursorPos(); Editor.InsertAtCursor(draft.Body);
        _revision = draft.Revision; _dirty = draft.Dirty; _loading = false; _confirmDelete = false; Refresh();
    }
    private void Changed()
    {
        if (_loading) return;
        _dirty = true; _confirmDelete = false; Refresh();
    }
    private void Refresh()
    {
        var remote = _entries.FirstOrDefault(entry => entry.Id == _selected);
        var conflict = !_new && _dirty && remote?.Revision != _revision;
        Status.Text = conflict ? Loc.GetString("pda-notes-conflict") : (_dirty ? Loc.GetString("pda-notes-unsaved") + " · " : "") + Body.Length + "/4000";
        Status.ToolTip = Status.Text;
        ReloadNote.Visible = conflict;
        SaveNote.Disabled = _pending != Guid.Empty || !_dirty || conflict || Body.Length > 4000 || NoteTitle.Text.Length > 80;
        DeleteNote.Disabled = _new || _pending != Guid.Empty;
        NewNote.Disabled = _pending != Guid.Empty;
        if (!_confirmDelete) DeleteNote.Text = Loc.GetString("pda-notes-delete");
    }
    private void Save()
    {
        if (SaveNote.Disabled) return;
        _pending = Guid.NewGuid(); _sent = new(NoteTitle.Text, Body, _revision, _dirty);
        var title = string.IsNullOrWhiteSpace(NoteTitle.Text) ? Loc.GetString("pda-notes-untitled") : NoteTitle.Text;
        OnAction?.Invoke(new(_new ? NotekeeperUiAction.Add : NotekeeperUiAction.Edit, Body, title, _selected, _revision, _pending));
        Refresh();
    }
    public void UpdateState(NotekeeperUiState state)
    {
        _entries = state.Entries;
        var acknowledged = _pending != Guid.Empty && state.Request == _pending;
        if (acknowledged)
        {
            if (state.Feedback == "pda-notes-saved")
            {
                if (_sent == null)
                {
                    _drafts.Remove(_selected); _selected = Guid.Empty; _new = true; _dirty = false;
                    _drafts.Remove(Guid.Empty); Load();
                }
                else
                {
                    var same = NoteTitle.Text == _sent.Title && Body == _sent.Body;
                    if (_new) { _drafts.Remove(Guid.Empty); _selected = state.Selected; _new = false; }
                    _revision = _entries.FirstOrDefault(entry => entry.Id == _selected)?.Revision ?? _revision;
                    _dirty = !same;
                    SaveDraft(); if (same) Load();
                }
            }
            _pending = Guid.Empty; _sent = null;
        }
        else if (!_dirty && !_new) Load();
        BuildList(); Refresh();
        if (acknowledged && state.Feedback != null && state.Feedback != "pda-notes-saved") Status.Text = Loc.GetString(state.Feedback);
    }
    public void UpdateState(List<string> notes)
    {
        UpdateState(new NotekeeperUiState(notes) { Entries = notes.Select(note => new NotekeeperEntry { Title = note.Split('\n')[0], Body = note }).ToArray() });
        if (_entries.Length > 0) Select(_entries[0].Id);
    }
    private void BuildList()
    {
        NoteList.RemoveAllChildren();
        foreach (var entry in _entries.Where(entry => entry.Title.Contains(Search.Text, StringComparison.CurrentCultureIgnoreCase) || entry.Body.Contains(Search.Text, StringComparison.CurrentCultureIgnoreCase)))
        {
            var button = new ContainerButton { StyleClasses = { "button" }, ToggleMode = true, Pressed = entry.Id == _selected, HorizontalExpand = true, ToolTip = entry.Title };
            button.AddChild(new BoxContainer { Orientation = LayoutOrientation.Vertical, Margin = new Thickness(3), SeparationOverride = 2, Children =
            {
                new Label { Text = entry.Title, ClipText = true, StyleClasses = { "pda-caption" } },
                new Label { Text = entry.Body.Replace('\n', ' '), ClipText = true, StyleClasses = { "terminal-muted" } },
            } });
            button.OnPressed += _ => Select(entry.Id); NoteList.AddChild(button);
        }
    }
}
