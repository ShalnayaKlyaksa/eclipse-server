using System.Linq;
using Content.Client.PDA;
using Content.Shared.CriminalRecords.Systems;
using Content.Shared.Security;
using Content.Shared.StatusIcon;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client.CartridgeLoader.Cartridges;

[GenerateTypedNameReferences]
public sealed partial class WantedListUiFragment : BoxContainer
{
    private string? _selectedTargetName;
    private List<WantedRecord> _wantedRecords = new();
    public WantedListUiFragment()
    {
        RobustXamlLoader.Load(this);
        SearchBar.OnTextChanged += _ => UpdateState(_wantedRecords, false);
    }
    public void UpdateState(List<WantedRecord> records, bool refresh = true)
    {
        if (refresh) _wantedRecords = records.ToList();
        var visible = _wantedRecords.Where(record => record.TargetInfo.Name.Contains(SearchBar.Text, StringComparison.CurrentCultureIgnoreCase) ||
            Loc.GetString("wanted-list-status-label", ("status", record.Status.ToString().ToLowerInvariant())).Contains(SearchBar.Text, StringComparison.CurrentCultureIgnoreCase)).ToArray();
        NoRecords.Visible = visible.Length == 0;
        RecordsList.Visible = ListDivider.Visible = visible.Length > 0;
        RecordUnselected.Visible = visible.Length > 0;
        PersonContainer.Visible = false; RecordButtons.RemoveAllChildren();
        foreach (var record in visible)
        {
            var button = new ContainerButton { HorizontalExpand = true, ToggleMode = true, Pressed = record.TargetInfo.Name == _selectedTargetName, StyleClasses = { "button" }, ToolTip = record.TargetInfo.Name };
            var row = new BoxContainer { HorizontalExpand = true, SeparationOverride = 4, Margin = new Thickness(2) };
            var iconId = "SecurityIcon" + (record.Status == SecurityStatus.Detained ? "Incarcerated" : record.Status.ToString());
            if (IoCManager.Resolve<IPrototypeManager>().TryIndex<SecurityIconPrototype>(iconId, out var icon))
                row.AddChild(new TextureRect { Texture = IoCManager.Resolve<IEntityManager>().System<SpriteSystem>().Frame0(icon.Icon), SetSize = new(20, 20), CanShrink = true, Stretch = TextureRect.StretchMode.KeepAspectCentered, VerticalAlignment = VAlignment.Center });
            var status = new RichTextLabel { HorizontalExpand = true }; status.SetMessage(Message("wanted-list-status-label", ("status", record.Status.ToString().ToLowerInvariant())));
            row.AddChild(new BoxContainer { Orientation = LayoutOrientation.Vertical, HorizontalExpand = true, Children = { new Label { Text = record.TargetInfo.Name, ClipText = true, StyleClasses = { "pda-caption" } }, status } });
            button.AddChild(row); button.OnPressed += _ => { _selectedTargetName = record.TargetInfo.Name; UpdateState(_wantedRecords, false); };
            RecordButtons.AddChild(button);
        }
        var selected = Array.FindIndex(visible, record => record.TargetInfo.Name == _selectedTargetName);
        if (selected >= 0) ShowRecord(visible[selected]);
    }
    private static FormattedMessage Message(string key, params (string, object)[] args)
    {
        args = args.Select(arg => (arg.Item1, arg.Item2 is string text ? (object) FormattedMessage.EscapeText(text) : arg.Item2)).ToArray();
        return FormattedMessage.FromMarkupPermissive(Loc.GetString(key, args));
    }
    private void ShowRecord(WantedRecord record)
    {
        PersonName.Text = PersonName.ToolTip = record.TargetInfo.Name;
        TargetAge.SetMessage(Message("wanted-list-age-label", ("age", record.TargetInfo.Age)));
        TargetJob.SetMessage(Message("wanted-list-job-label", ("job", record.TargetInfo.JobTitle)));
        TargetSpecies.SetMessage(Message("wanted-list-species-label", ("species", record.TargetInfo.Species)));
        var pronouns = Loc.GetString("humanoid-profile-editor-pronouns-" + record.TargetInfo.Gender.ToString().ToLowerInvariant() + "-text");
        TargetGender.SetMessage(Message("wanted-list-gender-label", ("gender", pronouns)));
        WantedReason.SetMessage(Message("wanted-list-reason-label", ("reason", record.Reason ?? Loc.GetString("wanted-list-unknown-reason-label"))));
        PersonState.SetMessage(Message("wanted-list-status-label", ("status", record.Status.ToString().ToLowerInvariant())));
        InitiatorName.SetMessage(Message("wanted-list-initiator-label", ("initiator", record.Initiator ?? Loc.GetString("wanted-list-unknown-initiator-label"))));
        HistoryTable.RemoveAllChildren(); HistoryTable.Visible = record.History.Count > 0;
        foreach (var history in record.History.OrderByDescending(entry => entry.AddTime))
        {
            var body = new BoxContainer { Orientation = LayoutOrientation.Vertical, HorizontalExpand = true, SeparationOverride = 3 };
            body.AddChild(new Label { Text = history.AddTime.ToString(@"hh\:mm\:ss") + " · " + (history.InitiatorName ?? Loc.GetString("wanted-list-unknown-initiator-label")), ClipText = true, ToolTip = history.InitiatorName, StyleClasses = { "terminal-muted" } });
            var reason = new RichTextLabel { HorizontalExpand = true }; reason.SetMessage(FormattedMessage.FromUnformatted(history.Crime)); body.AddChild(reason);
            var card = PdaAppUi.Card(body); card.HorizontalExpand = true; HistoryTable.AddChild(card);
        }
        RecordUnselected.Visible = false; PersonContainer.Visible = true; _selectedTargetName = record.TargetInfo.Name;
    }
}
