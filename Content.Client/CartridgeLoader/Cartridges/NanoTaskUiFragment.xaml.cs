using System.Linq;
using Content.Client.PDA;
using Content.Shared.CartridgeLoader.Cartridges;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.CartridgeLoader.Cartridges;

[GenerateTypedNameReferences]
public sealed partial class NanoTaskUiFragment : BoxContainer
{
    public Action<int>? ToggleTaskCompletion;
    public List<NanoTaskItemAndId> Tasks = new();
    public NanoTaskUiFragment()
    {
        RobustXamlLoader.Load(this);
        NewTaskButton.OnPressed += _ => Editor.Select(null, null);
        Search.OnTextChanged += _ => Rebuild(); ShowDone.OnPressed += _ => Rebuild();
    }
    public void UpdateState(List<NanoTaskItemAndId> tasks)
    {
        Editor.ObserveTasks(tasks, Tasks.Select(task => task.Id).ToHashSet());
        Tasks = tasks; Rebuild();
    }
    private void Rebuild()
    {
        TaskList.RemoveAllChildren();
        var visible = Tasks.Where(task => (ShowDone.Pressed || !task.Data.IsTaskDone) &&
            (task.Data.Description.Contains(Search.Text, StringComparison.CurrentCultureIgnoreCase) || task.Data.TaskIsFor.Contains(Search.Text, StringComparison.CurrentCultureIgnoreCase))).ToArray();
        foreach (var priority in new[] { NanoTaskPriority.High, NanoTaskPriority.Medium, NanoTaskPriority.Low })
        {
            var tasks = visible.Where(task => task.Data.Priority == priority).ToArray(); if (tasks.Length == 0) continue;
            var key = priority.ToString().ToLowerInvariant();
            TaskList.AddChild(new Label { Text = Loc.GetString("nano-task-ui-heading-" + key + "-priority-tasks", ("amount", tasks.Length)), StyleClasses = { "pda-caption" } });
            foreach (var task in tasks)
            {
                var row = new NanoTaskItemControl(task, Editor.EditingId == task.Id) { HorizontalExpand = true };
                row.OnMainPressed += id => { Editor.Select(id, task.Data); Rebuild(); };
                row.OnDonePressed += id => { Editor.UpdateCompletion(id, !task.Data.IsTaskDone); ToggleTaskCompletion?.Invoke(id); };
                TaskList.AddChild(row);
            }
        }
        if (visible.Length == 0) TaskList.AddChild(PdaAppUi.Empty(Loc.GetString("pda-tasks-empty"), Loc.GetString("pda-tasks-new-hint")));
    }
}
