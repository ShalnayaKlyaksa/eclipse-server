using System.Linq;
using Content.Client.PDA;
using Content.Shared.CartridgeLoader.Cartridges;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.CartridgeLoader.Cartridges;

[GenerateTypedNameReferences]
public sealed partial class LogProbeUiFragment : BoxContainer
{
    public Action? OnPrintPressed;
    private PulledAccessLog[] _logs = [];
    public LogProbeUiFragment()
    {
        RobustXamlLoader.Load(this);
        PrintButton.OnPressed += _ => OnPrintPressed?.Invoke();
        Search.OnTextChanged += _ => Rebuild(); Rebuild();
    }
    public void UpdateState(string name, List<PulledAccessLog> logs)
    {
        EntityName.Text = EntityName.ToolTip = name;
        PrintButton.Disabled = string.IsNullOrEmpty(name);
        if (_logs.SequenceEqual(logs)) return;
        _logs = logs.ToArray(); Rebuild();
    }
    private void Rebuild()
    {
        ProbedDeviceContainer.RemoveAllChildren(); var count = 0;
        for (var i = 0; i < _logs.Length; i++)
        {
            var log = _logs[i]; var time = log.Time.ToString(@"hh\:mm\:ss");
            if (!log.Accessor.Contains(Search.Text, StringComparison.CurrentCultureIgnoreCase) && !time.Contains(Search.Text, StringComparison.Ordinal)) continue;
            var row = new BoxContainer { HorizontalExpand = true, SeparationOverride = 6, Margin = new Thickness(4, 2) };
            row.AddChild(new Label { Text = (i + 1).ToString(), SetWidth = 32, Align = Label.AlignMode.Right });
            row.AddChild(new Label { Text = time, SetWidth = 100, StyleClasses = { "terminal-muted" } });
            var person = new RichTextLabel { HorizontalExpand = true };
            person.SetMessage(Robust.Shared.Utility.FormattedMessage.FromUnformatted(log.Accessor), PdaTheme.TextColor); row.AddChild(person);
            var button = new ContainerButton { HorizontalExpand = true, StyleClasses = { "button" }, ToolTip = Loc.GetString("pda-log-copy-hint"), Children = { row } };
            button.OnPressed += _ => IoCManager.Resolve<IClipboardManager>().SetText(time + " · " + log.Accessor);
            ProbedDeviceContainer.AddChild(button); count++;
        }
        Count.Text = count + "/" + _logs.Length;
        if (count == 0) ProbedDeviceContainer.AddChild(PdaAppUi.Empty(Loc.GetString("pda-log-empty"), Loc.GetString("pda-log-scan-hint")));
    }
}
