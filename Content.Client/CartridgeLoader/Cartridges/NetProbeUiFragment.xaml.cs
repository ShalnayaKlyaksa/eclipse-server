using System.Linq;
using Content.Client.PDA;
using Content.Shared.CartridgeLoader.Cartridges;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.CartridgeLoader.Cartridges;

[GenerateTypedNameReferences]
public sealed partial class NetProbeUiFragment : BoxContainer
{
    private ProbedNetworkDevice[] _devices = [];
    public NetProbeUiFragment()
    {
        RobustXamlLoader.Load(this);
        Search.OnTextChanged += _ => Rebuild();
        Rebuild();
    }
    public void UpdateState(List<ProbedNetworkDevice> devices)
    {
        if (_devices.SequenceEqual(devices)) return;
        _devices = devices.ToArray(); Rebuild();
    }
    private void Rebuild()
    {
        ProbedDeviceContainer.RemoveAllChildren();
        var devices = _devices.Reverse().Where(device => new[] { device.Name, device.Address, device.Frequency, device.NetId }
            .Any(value => value.Contains(Search.Text, StringComparison.CurrentCultureIgnoreCase))).ToArray();
        Count.Text = devices.Length + "/" + _devices.Length;
        foreach (var device in devices)
        {
            var row = new BoxContainer { HorizontalExpand = true, SeparationOverride = 6, Margin = new Thickness(4, 2) };
            row.AddChild(new Label { Text = device.Name, ToolTip = device.Name, ClipText = true, MinWidth = 100, HorizontalExpand = true });
            var address = PdaAppUi.Action(device.Address); address.SetWidth = 135; address.ClipText = true; address.ToolTip = device.Address;
            address.OnPressed += _ => IoCManager.Resolve<IClipboardManager>().SetText(device.Address); row.AddChild(address);
            row.AddChild(new Label { Text = device.Frequency, ToolTip = device.Frequency, SetWidth = 100, ClipText = true });
            row.AddChild(new Label { Text = device.NetId, ToolTip = device.NetId, SetWidth = 100, ClipText = true });
            ProbedDeviceContainer.AddChild(row);
            ProbedDeviceContainer.AddChild(new PanelContainer { MinHeight = 1, StyleClasses = { "pda-divider" } });
        }
        if (devices.Length == 0) ProbedDeviceContainer.AddChild(PdaAppUi.Empty(Loc.GetString("pda-net-empty"), Loc.GetString("pda-net-scan-hint")));
    }
}
